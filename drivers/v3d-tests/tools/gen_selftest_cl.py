"""Generates drivers/src/v3d/selftest_cl.rs: a render-only RCL (bcl_start == bcl_end) that clears a
64x64 RGBA8UI frame (2x2 tiles of 32x32) and stores it linear (raster, stride 256) into the same BO.

Mirrors Mesa 25.3.6 v3dvx_meta_common.c `meta_emit_fill_buffer_rcl` for V3D 7.1, except the generic
tile list has no BRANCH_TO_IMPLICIT_TILE_LIST: with no binning job the tile lists are never written.

    python3 -I gen_selftest_cl.py <mesa>/src/broadcom/cle/v3d_packet.xml > ../../src/v3d/selftest_cl.rs
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import clpack

s = clpack.Spec(sys.argv[1])
W = H = 64
TILE = 32
TILES = W // TILE
RCL_OFF, GTL_OFF, TLB_OFF, IMG_OFF, BO_SIZE = 0x0, 0x400, 0x800, 0x1000, 0x8000
STRIDE = W * 4

def build(items, base):
    out = bytearray(); patches = []
    for name, kv in items:
        b, addrs = s.pack(name, **kv)
        patches += [base + len(out) + o for o in addrs.values()]
        out += b
    return out, patches

gtl, p1 = build([
    ('Tile Coordinates Implicit', {}),
    ('End of Loads', {}),
    ('Store Tile Buffer General', dict(buffer_to_store=0, address=IMG_OFF, clear_buffer_being_stored=0,
        output_image_format='rgba8ui', memory_format='raster', height_in_ub_or_stride=STRIDE,
        decimate_mode='sample_0')),
    ('End of Tile Marker', {}),
    ('Return from sub-list', {}),
], GTL_OFF)

items = [
    ('Tile Rendering Mode Cfg (Common)', dict(early_z_disable=1, image_width_pixels=W, image_height_pixels=H,
        number_of_render_targets=1, log2_tile_width=2, log2_tile_height=2, internal_depth_type='depth_32f')),
    ('Tile Rendering Mode Cfg (Render Target Part1)', dict(clear_color_low_bits=0xCAFE5A3C, internal_bpp='32',
        internal_type_and_clamping='8ui', stride=TILE * 1 // 2, base_address=0, render_target_number=0)),
    ('Tile Rendering Mode Cfg (ZS clear values)', dict(z_clear_value=1.0, stencil_clear_value=0)),
    ('Tile List Initial Block Size', dict(use_auto_chained_tile_lists=1, size_of_first_block_in_chained_tile_lists=0)),
    ('Multicore Rendering Tile List Set Base', dict(address=TLB_OFF, tile_list_set_number=0)),
    ('Multicore Rendering Supertile Cfg', dict(number_of_bin_tile_lists=1, total_frame_width_in_tiles=TILES,
        total_frame_height_in_tiles=TILES, supertile_width_in_tiles=1, supertile_height_in_tiles=1,
        total_frame_width_in_supertiles=TILES, total_frame_height_in_supertiles=TILES)),
]
for i in range(2):  # GFXH-1742: two dummy tiles; the first one clears the render targets
    items += [('Tile Coordinates', {}), ('End of Loads', {}), ('Store Tile Buffer General', dict(buffer_to_store=8))]
    if i == 0:
        items.append(('Clear Render Targets', {}))
    items.append(('End of Tile Marker', {}))
items.append(('Flush VCD cache', {}))
items.append(('Start Address of Generic Tile List', dict(start=GTL_OFF, end=GTL_OFF + len(gtl))))
for y in range(TILES):
    for x in range(TILES):
        items.append(('Supertile Coordinates', dict(column_number_in_supertiles=x, row_number_in_supertiles=y)))
items.append(('End of rendering', {}))
rcl, p2 = build(items, RCL_OFF)
assert len(rcl) <= GTL_OFF and len(gtl) <= TLB_OFF - GTL_OFF

def arr(b):
    return ',\n'.join('    ' + ', '.join('0x%02x' % x for x in b[i:i + 12]) for i in range(0, len(b), 12))

print('''//! GENERATED by drivers/v3d-tests/tools/gen_selftest_cl.py from Mesa 25.3.6 cle/v3d_packet.xml (V3D 7.1).
//! Do not edit by hand. A render-only RCL that clears a 64x64 RGBA8UI frame to `CLEAR_COLOR` and
//! stores it linear at `IMG_OFF` (stride 256). Address words hold BO-relative offsets; `PATCHES` lists
//! the byte offsets (within the BO) of every 32-bit address word, to which the BO's GPU VA is added.
''')
print('pub const W: u32 = %d;\npub const H: u32 = %d;\npub const STRIDE: u32 = %d;' % (W, H, STRIDE))
print('pub const CLEAR_COLOR: u32 = 0xCAFE5A3C;')
print('pub const RCL_OFF: usize = 0x%x;\npub const GTL_OFF: usize = 0x%x;\npub const TLB_OFF: usize = 0x%x;' % (RCL_OFF, GTL_OFF, TLB_OFF))
print('pub const IMG_OFF: usize = 0x%x;\npub const BO_SIZE: usize = 0x%x;' % (IMG_OFF, BO_SIZE))
print('pub const RCL: [u8; %d] = [\n%s,\n];' % (len(rcl), arr(rcl)))
print('pub const GTL: [u8; %d] = [\n%s,\n];' % (len(gtl), arr(gtl)))
pp = p1 + p2
print('pub const PATCHES: [usize; %d] = [%s];' % (len(pp), ', '.join('0x%x' % p for p in sorted(pp))))
