#!/usr/bin/env python3
"""Generate drivers/src/bcm2712_pinctrl_tables.rs from Linux pinctrl-bcm2712.c.

Usage: gen-bcm2712-pinctrl.py <path/to/pinctrl-bcm2712.c> > drivers/src/bcm2712_pinctrl_tables.rs

Source: raspberrypi/linux rpi-6.6.y, drivers/pinctrl/bcm/pinctrl-bcm2712.c.
"""
import re
import sys

src = open(sys.argv[1]).read()


def block(name):
    m = re.search(r'\b' + re.escape(name) + r'\[\]\s*=\s*\{(.*?)\n\};', src, re.S)
    if not m:
        sys.exit('missing table ' + name)
    return m.group(1)


enum = re.search(r'enum bcm2712_funcs \{(.*?)\};', src, re.S).group(1)
funcs = [f.strip()[5:] for f in enum.split(',') if f.strip().startswith('func_') and '=' not in f]
assert funcs[0] == 'gpio' and funcs[-1] == '_', funcs[-1]
funcs = funcs[:-1]  # drop func__ (== func_count)
fid = {f: i for i, f in enumerate(funcs)}
NONE_F = 0xFF


def regs(name):
    out = {}
    for m in re.finditer(r'(GPIO|AGPIO|EMMC|SGPIO)_REGS\(([^)]*)\)', block(name)):
        kind, a = m.group(1), [int(x) for x in m.group(2).split(',')]
        if kind in ('GPIO', 'AGPIO'):
            n, mr, mb, pr, pb = a
            out[n] = ((mr * 4) * 8 + mb * 4, (pr * 4) * 8 + pb * 2)
        elif kind == 'EMMC':
            n, pr, pb = a
            out[n] = (None, (pr * 4) * 8 + pb * 2)
        else:
            n, mr, mb = a
            out[n + 32] = ((mr * 4) * 8 + mb * 4, None)
    return out


def pins(name):
    out = []
    for m in re.finditer(r'(GPIO_PIN|AGPIO_PIN|SGPIO_PIN|PINCTRL_PIN)\(([^)]*)\)', block(name)):
        kind, a = m.group(1), m.group(2)
        if kind == 'GPIO_PIN':
            n = int(a); out.append((n, 'gpio%d' % n))
        elif kind == 'AGPIO_PIN':
            n = int(a); out.append((n, 'aon_gpio%d' % n))
        elif kind == 'SGPIO_PIN':
            n = int(a); out.append((n + 32, 'aon_sgpio%d' % n))
        else:
            n, nm = a.split(',', 1)
            out.append((int(n), nm.strip().strip('"')))
    return out


def pfuncs(name, off=0):
    out = {}
    for m in re.finditer(r'PIN\(([^)]*)\)', block(name)):
        a = [x.strip() for x in m.group(1).split(',')]
        out[int(a[0]) + off] = [NONE_F if f == '_' else fid[f] for f in a[1:]]
        assert len(out[int(a[0]) + off]) == 8
    return out


def emit(rust, pinst, regt, fts):
    p = pins(pinst)
    r = regs(regt)
    f = {}
    for t, off in fts:
        f.update(pfuncs(t, off))
    print('pub static %s: [Pin; %d] = [' % (rust, len(p)))
    for n, nm in p:
        mux, pad = r.get(n, (None, None))
        fl = f.get(n, [0] * 8)  # Linux: a missing PIN() row is all func_gpio
        h = lambda v: 'NONE' if v is None else '0x%04x' % v
        print('    Pin { num: %d, name: "%s", mux: %s, pad: %s, funcs: [%s] },'
              % (n, nm, h(mux), h(pad), ', '.join('0x%02x' % x for x in fl)))
    print('];')


print('// Generated by scripts/gen-bcm2712-pinctrl.py from Linux pinctrl-bcm2712.c')
print('// (raspberrypi/linux rpi-6.6.y). Do not edit by hand.')
print('//! BCM2712 pin-mux tables: C0 (also C1) and D0, main and always-on blocks.')
print()
print('/// Bit offsets into the block (register = off / 32 * 4, shift = off % 32), or NONE.')
print('pub const NONE: u16 = 0xFFFF;')
print('/// `funcs[k]` = function id selected by fsel k+1; 0xFF = no function.')
print('pub const NO_FUNC: u8 = 0x%02X;' % NONE_F)
print('#[derive(Clone, Copy, Debug)]')
print('pub struct Pin { pub num: u8, pub name: &\'static str, pub mux: u16, pub pad: u16, pub funcs: [u8; 8] }')
print()
print('/// Function names by id (Linux `enum bcm2712_funcs`): 0 = gpio, 1..=8 = alt1..alt8 (raw fsel).')
print('pub const FUNC_NAMES: [&str; %d] = [' % len(funcs))
for i in range(0, len(funcs), 6):
    print('    ' + ' '.join('"%s",' % x for x in funcs[i:i + 6]))
print('];')
print()
emit('C0_MAIN', 'bcm2712_c0_gpio_pins', 'bcm2712_c0_gpio_pin_regs', [('bcm2712_c0_gpio_pin_funcs', 0)])
emit('C0_AON', 'bcm2712_c0_aon_gpio_pins', 'bcm2712_c0_aon_gpio_pin_regs',
     [('bcm2712_c0_aon_gpio_pin_funcs', 0), ('bcm2712_c0_aon_sgpio_pin_funcs', 32)])
emit('D0_MAIN', 'bcm2712_d0_gpio_pins', 'bcm2712_d0_gpio_pin_regs', [('bcm2712_d0_gpio_pin_funcs', 0)])
emit('D0_AON', 'bcm2712_d0_aon_gpio_pins', 'bcm2712_d0_aon_gpio_pin_regs',
     [('bcm2712_d0_aon_gpio_pin_funcs', 0), ('bcm2712_d0_aon_sgpio_pin_funcs', 32)])
