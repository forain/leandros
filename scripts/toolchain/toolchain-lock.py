#!/usr/bin/env python3
"""Build-only Alpine apks for the clang/musl target sysroot (stdlib only).

  toolchain-lock.py refresh            re-pin ports/alpine/toolchain.lock against the cached/online APKINDEX
  toolchain-lock.py extract <arch> <dir>   fetch (sha256-verified) and unpack every locked apk of <arch> into <dir>
  toolchain-lock.py print <arch> <name>    print the locked version of a package

Lock line: pkg <arch> <name> <ver> <repo> <C:Q1..> <sha256 of the .apk>
musl and musl-dev are pinned to the version of the image's ports/alpine/<arch>.lock
(static headers/libc must equal the runtime libc); refresh fails otherwise.
Reuses scripts/alpine-lock.py (cache, download, checksums). Never part of the image world.
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.dirname(HERE)
spec = importlib.util.spec_from_file_location("alock", os.path.join(SCRIPTS, "alpine-lock.py"))
A = importlib.util.module_from_spec(spec)
sys.path.insert(0, SCRIPTS)
spec.loader.exec_module(A)

LOCK = os.path.join(A.ADIR, "toolchain.lock")
PKGS = ["musl", "musl-dev", "linux-headers", "compiler-rt", "llvm-libunwind-static",
        "llvm-libunwind-dev", "libc++", "libc++-dev", "libc++-static"]


def read():
    rel, ent = "", {}
    for line in open(LOCK):
        t = line.split()
        if not t:
            continue
        if t[0] == "#" and len(t) > 2 and t[1] == "release":
            rel = t[2]
        elif t[0] == "pkg":
            ent.setdefault(t[1], {})[t[2]] = {"name": t[2], "ver": t[3], "repo": t[4], "C": t[5],
                                              "sha256": t[6], "scripts": []}
    return rel, ent


def refresh():
    rel = A.lock_release("aarch64")
    A.REL = rel
    out = ["# release %s" % rel,
           "# Build-only apks for scripts/toolchain (clang target sysroot); NOT in the image world.",
           "# generated by scripts/toolchain/toolchain-lock.py refresh"]
    for arch in A.ARCHS:
        img, _, _ = A.read_lock(arch)
        A.REL = rel
        idx = A.load_index(arch, True)
        for n in PKGS:
            q = idx.get(n) or A.die("%s not in %s/%s" % (n, rel, arch))
            if n in ("musl", "musl-dev") and q["ver"] != img["musl"]["ver"]:
                A.die("%s %s in the index != image musl %s" % (n, q["ver"], img["musl"]["ver"]))
            p = {"name": n, "ver": q["ver"], "repo": q["repo"]}
            f = A.apk_path(arch, p)
            if not os.path.exists(f):
                A.download("%s/%s/%s/%s/%s" % (A.MIRROR, rel, q["repo"], arch, A.apk_name(p)), f)
            c, _ = A.control_info(f)
            out.append("pkg %s %s %s %s %s %s" % (arch, n, q["ver"], q["repo"], c, A.sha256_file(f)))
    open(LOCK, "w").write("\n".join(out) + "\n")
    print("wrote", LOCK)


def extract(arch, dest):
    rel, ent = read()
    A.REL = rel
    os.makedirs(dest, exist_ok=True)
    for n in PKGS:
        p = ent[arch][n]
        f = A.apk_path(arch, p)
        if not os.path.exists(f):
            A.download("%s/%s/%s/%s/%s" % (A.MIRROR, rel, p["repo"], arch, A.apk_name(p)), f)
        got = A.sha256_file(f)
        if got != p["sha256"]:
            os.unlink(f)
            A.die("%s: sha256 %s != toolchain.lock (cache entry removed)" % (A.apk_name(p), got))
        d = A.extract_one(arch, p)
        # one dir per package under <dest>/<name>; mk-sysroot.sh merges them
        os.system("rm -rf '%s/%s' && mkdir -p '%s/%s' && cp -R '%s/.' '%s/%s/' && rm -f '%s/%s/.done'"
                  % (dest, n, dest, n, d, dest, n, dest, n))
        print("%s %s %s" % (arch, n, p["ver"]))


if __name__ == "__main__":
    c = sys.argv[1] if len(sys.argv) > 1 else ""
    if c == "refresh":
        refresh()
    elif c == "extract":
        extract(sys.argv[2], sys.argv[3])
    elif c == "print":
        print(read()[1][sys.argv[2]][sys.argv[3]]["ver"])
    else:
        A.die(__doc__)
