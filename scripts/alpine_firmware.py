#!/usr/bin/env python3
"""Firmware blobs for the LeandrOS image come from Alpine's linux-firmware-* / bluez-firmware packages.

  alpine_firmware.py refresh [--cached]   resolve ports/alpine/firmware.list against the locked Alpine release
                                          and write ports/alpine/firmware.lock (apk sha256 pins)
  alpine_firmware.py fetch   <arch>       download + verify the locked apks (cache: ~/.cache/leandros/apk)
  alpine_firmware.py stage   <arch>       fetch, then materialise ONLY the listed files, decompressed, under
                                          <fwcache>/<arch>/lib/firmware/... (prints one line per file)
  alpine_firmware.py check                exit 1 when a locked firmware package has a newer version
  alpine_firmware.py selftest <arch>

ports/alpine/firmware.list: `<arch> <package> <member path in the apk> <dest under /lib/firmware, plain | - >`.
Alpine ships every blob zstd-compressed (`*.zst`) and uses symlinks (also across subpackages, e.g.
brcm/ -> ../cypress/); the member path is resolved through the symlinks of all listed packages and a
trailing `.zst` is decompressed at stage time, so the kernel (which has no zstd loader) sees the same
plain files it always requested. Only the listed files are staged: linux-firmware-intel alone is 120 MB.
These files are not tracked in the apk db of the image (they are not part of the world).

firmware.lock: `# release vX.Y`, then `fw <arch> <name> <ver> <repo> <sha256 of the .apk>`.
The release is the one of ports/alpine/<arch>.lock; stdlib only (zstd via compression.zstd or the zstd CLI).
"""
import hashlib
import importlib.util
import io
import os
import posixpath
import shutil
import subprocess
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import apkdb  # noqa: E402

_spec = importlib.util.spec_from_file_location("alpine_lock", os.path.join(HERE, "alpine-lock.py"))
lk = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(lk)

LIST = os.path.join(lk.ADIR, "firmware.list")
LOCK = os.path.join(lk.ADIR, "firmware.lock")
FWCACHE = os.environ.get("LEANDROS_FW_CACHE", os.path.expanduser(
    os.path.join(os.environ.get("XDG_CACHE_HOME", "~/.cache"), "leandros/alpine-fw")))
die = lk.die


def read_list(arch=None):
    out = []
    for line in open(LIST):
        t = line.split("#")[0].split()
        if not t:
            continue
        if len(t) != 4:
            die("bad firmware.list line: " + line.strip())
        if arch is None or t[0] == arch:
            out.append(dict(zip(("arch", "pkg", "src", "dest"), t)))
    return out


def read_lock():
    rel, pkgs = "", {}
    if not os.path.exists(LOCK):
        die("%s missing; run: alpine_firmware.py refresh" % LOCK)
    for line in open(LOCK):
        t = line.split()
        if not t:
            continue
        if t[0] == "#" and len(t) > 2 and t[1] == "release":
            rel = t[2]
        elif t[0] == "fw":
            pkgs[(t[1], t[2])] = {"name": t[2], "ver": t[3], "repo": t[4], "sha256": t[5]}
    return rel, pkgs


def zstd_decompress(b):
    try:
        from compression import zstd
        return zstd.decompress(b)
    except ImportError:
        pass
    r = subprocess.run(["zstd", "-dc"], input=b, stdout=subprocess.PIPE, check=False)
    if r.returncode:
        die("zstd -d failed (need python >= 3.14 or the zstd CLI)")
    return r.stdout


def cmd_refresh(cached):
    rel = lk.lock_release("x86_64")
    if not rel or rel != lk.lock_release("aarch64"):
        die("x86_64.lock and aarch64.lock disagree on the release")
    lk.REL = rel
    lines = ["# release %s" % rel,
             "# Alpine firmware pins for ports/alpine/firmware.list; generated by scripts/alpine_firmware.py refresh"]
    for arch in lk.ARCHS:
        names = sorted({e["pkg"] for e in read_list(arch)})
        if not names:
            continue
        idx = lk.load_index(arch, cached)
        for n in names:
            p = idx.get(n)
            if p is None:
                die("%s not in Alpine %s/%s" % (n, rel, arch))
            e = {"name": n, "ver": p["ver"]}
            f = lk.apk_path(arch, e)
            if not os.path.exists(f):
                lk.download("%s/%s/%s/%s/%s" % (lk.MIRROR, rel, p["repo"], arch, lk.apk_name(e)), f)
            c, _ = lk.control_info(f)
            if c != p["C"]:
                die("%s: control checksum %s != index %s" % (n, c, p["C"]))
            lines.append("fw %s %s %s %s %s" % (arch, n, p["ver"], p["repo"], lk.sha256_file(f)))
    open(LOCK, "w").write("\n".join(lines) + "\n")
    print("wrote %s (%d packages)" % (LOCK, len(lines) - 2))


def apk_file(arch, p):
    lk.REL = read_lock()[0]
    e = {"name": p["name"], "ver": p["ver"]}
    f = lk.apk_path(arch, e)
    if not os.path.exists(f):
        lk.download("%s/%s/%s/%s/%s" % (lk.MIRROR, lk.REL, p["repo"], arch, lk.apk_name(e)), f)
    got = lk.sha256_file(f)
    if got != p["sha256"]:
        os.unlink(f)
        die("%s: sha256 %s != lock %s (cache entry removed)" % (lk.apk_name(e), got, p["sha256"]))
    return f


def cmd_fetch(arch):
    _, pkgs = read_lock()
    for (a, n), p in sorted(pkgs.items()):
        if a == arch:
            apk_file(arch, p)
    print("%s: %d firmware packages ok, %d files staged" % (arch, sum(1 for k in pkgs if k[0] == arch), len(stage(arch))))


def stage(arch):
    """-> [(dest dir under the image root, file name, host path, src description)] after materialising them."""
    ents = read_list(arch)
    if not ents:
        return []
    files = [e for e in ents if e["dest"] != "-"]   # "-" only pulls the package in (cross-package symlink targets)
    _, pkgs = read_lock()
    key = hashlib.sha256()
    tars, members = {}, {}
    for n in sorted({e["pkg"] for e in ents}):
        p = pkgs.get((arch, n)) or die("%s not in firmware.lock; run refresh" % n)
        key.update(p["sha256"].encode())
    key.update(open(LIST, "rb").read())
    root = os.path.join(FWCACHE, arch, key.hexdigest()[:16])
    done = os.path.join(root, ".done")
    if not os.path.exists(done):
        for n in sorted({e["pkg"] for e in ents}):
            f = apk_file(arch, pkgs[(arch, n)])
            segs = apkdb._apk_segments(open(f, "rb").read())
            tf = tarfile.open(fileobj=io.BytesIO(segs[2][1]))
            tars[n] = tf
            for m in tf:
                members[m.name] = (tf, m)

        def resolve(path):
            for _ in range(8):
                if path not in members:
                    die("firmware member %s not found in the listed packages" % path)
                tf, m = members[path]
                if m.issym():
                    path = posixpath.normpath(posixpath.join(posixpath.dirname(path), m.linkname))
                elif m.islnk():
                    path = m.linkname
                else:
                    return tf, m, path
            die("symlink loop at " + path)

        shutil.rmtree(root, ignore_errors=True)
        for e in files:
            tf, m, real = resolve(e["src"])
            data = tf.extractfile(m).read()
            if real.endswith(".zst"):
                data = zstd_decompress(data)
            out = os.path.join(root, "lib/firmware", e["dest"])
            os.makedirs(os.path.dirname(out), exist_ok=True)
            with open(out, "wb") as fh:
                fh.write(data)
            os.chmod(out, 0o644)
        open(done, "w").close()
    link = os.path.join(FWCACHE, arch, "current")   # stable path for host tests (drivers/*-tests)
    try:
        if os.path.islink(link) or os.path.exists(link):
            os.unlink(link)
        os.symlink(os.path.basename(root), link)
    except OSError:
        pass
    res = []
    for e in files:
        d, name = posixpath.split(e["dest"])
        res.append(("/lib/firmware" + ("/" + d if d else ""), name,
                    os.path.join(root, "lib/firmware", e["dest"]), "%s:%s" % (e["pkg"], e["src"])))
    return res


def cmd_check():
    rel, pkgs = read_lock()
    lk.REL = rel
    stale = []
    for arch in lk.ARCHS:
        idx = lk.load_index(arch, False)
        for (a, n), p in sorted(pkgs.items()):
            if a == arch and lk.vcmp(idx[n]["ver"], p["ver"]) > 0:
                print("%s: %s %s -> %s" % (arch, n, p["ver"], idx[n]["ver"]))
                stale.append(n)
    print("firmware lock %s is %s" % (rel, "STALE" if stale else "current"))
    sys.exit(1 if stale else 0)


def main(argv):
    c = argv[1] if len(argv) > 1 else ""
    if c == "refresh":
        cmd_refresh("--cached" in argv)
    elif c == "check":
        cmd_check()
    elif c in ("fetch", "stage", "selftest") and len(argv) > 2 and argv[2] in lk.ARCHS:
        if c == "fetch":
            cmd_fetch(argv[2])
        else:
            for d, n, h, s in stage(argv[2]):
                print("%s/%s  %d  %s  <- %s" % (d, n, os.path.getsize(h), hashlib.sha256(open(h, "rb").read()).hexdigest(), s))
    else:
        die(__doc__)


if __name__ == "__main__":
    main(sys.argv)
