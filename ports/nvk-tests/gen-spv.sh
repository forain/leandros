#!/bin/sh
# gen-spv.sh — regenerate ports/nvk-tests/nvktest_spv.h from shaders/*.
#
# The header is committed so build.sh needs no shader compiler; run this only
# after editing a shader. glslc (Alpine `shaderc`) runs in an alpine:3.21
# container of the HOST architecture (inside LeandrOS: a chroot'ed Alpine root,
# scripts/container-lib.sh) (SPIR-V is arch-independent), emits
# Vulkan 1.0 SPIR-V as C initialisers (-mfmt=c), and each blob is checked for
# the SPIR-V magic 0x07230203 before the header is replaced.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
. "$HERE/../../scripts/container-lib.sh"
leandros_pick_alpine || { echo "no Alpine backend: $ALPINE_WHY"; exit 1; }

TMP=$(mktemp -d "${TMPDIR:-/tmp}/nvk-spv.XXXXXX")
trap 'rm -rf "$TMP"' EXIT
cp "$HERE"/shaders/add.comp "$HERE"/shaders/triangle.vert "$HERE"/shaders/triangle.frag "$TMP/"

leandros_alpine_run --image "${GPU_BUILD_IMAGE:-alpine:3.21}" -v "$TMP:/w" -- sh -c '
  set -e
  apk add --no-cache shaderc >/dev/null
  cd /w
  glslc --target-env=vulkan1.0 -O -fshader-stage=compute  -mfmt=c -o add.inc  add.comp
  glslc --target-env=vulkan1.0 -O -fshader-stage=vertex   -mfmt=c -o vert.inc triangle.vert
  glslc --target-env=vulkan1.0 -O -fshader-stage=fragment -mfmt=c -o frag.inc triangle.frag
  glslc --version | head -1 > version.txt
'

for f in add vert frag; do
  first=$(tr -d '{ \n\t' < "$TMP/$f.inc" | cut -d, -f1)
  [ "$first" = "0x07230203" ] || { echo "$f.inc: bad SPIR-V magic '$first'"; exit 1; }
done

OUT="$HERE/nvktest_spv.h"
{
  echo "/* GENERATED by ports/nvk-tests/gen-spv.sh — do not edit by hand."
  echo " * Compiler: $(cat "$TMP/version.txt")"
  echo " * Sources: shaders/add.comp, shaders/triangle.vert, shaders/triangle.frag */"
  echo "#pragma once"
  echo "#include <stdint.h>"
  printf 'static const uint32_t spv_add_comp[] = '; cat "$TMP/add.inc";  printf ';\n'
  printf 'static const uint32_t spv_tri_vert[] = '; cat "$TMP/vert.inc"; printf ';\n'
  printf 'static const uint32_t spv_tri_frag[] = '; cat "$TMP/frag.inc"; printf ';\n'
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "wrote $OUT ($(grep -c 0x07230203 "$OUT") SPIR-V blobs)"
