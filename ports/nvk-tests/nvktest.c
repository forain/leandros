/* The single place a fence is waited on. Finite timeout, always.
 * `pnext`/`sig` let the timeline subtest attach a semaphore signal. */
static wait_res submit_and_wait(const char *tag, const void *pnext,
                                const VkSemaphore *sig, int wait_fence_after_sem,
                                const uint64_t *sem_value)
{
    STEP("vkResetFences");
    VkResult r = vkResetFences_(g_device, 1, &g_fence);
    if (r != VK_SUCCESS) {
        ERR("%s: vkResetFences -> %s", tag, vk_result_str(r));
        why("vkResetFences -> %s", vk_result_str(r));
        return WAIT_ERROR;
    }
    VkSubmitInfo si = {
        .sType = VK_STRUCTURE_TYPE_SUBMIT_INFO,
        .pNext = pnext,
        .commandBufferCount = 1,
        .pCommandBuffers = &g_cb,
        .signalSemaphoreCount = sig ? 1u : 0u,
        .pSignalSemaphores = sig,
    };
    STEP("vkQueueSubmit");
    uint64_t t0 = now_us();
    r = vkQueueSubmit_(g_queue, 1, &si, g_fence);
    uint64_t t1 = now_us();
    if (r != VK_SUCCESS) {
        ERR("%s: vkQueueSubmit -> %s (after %.2f ms)", tag, vk_result_str(r), MS(t1 - t0));
        why("vkQueueSubmit -> %s", vk_result_str(r));
        if (r == VK_ERROR_DEVICE_LOST) g_device_lost = 1;
        return WAIT_ERROR;
    }
    INFO("%s: vkQueueSubmit returned in %.2f ms", tag, MS(t1 - t0));

    uint64_t timeout_ns = g_timeout_ms * 1000000ull;

    if (wait_fence_after_sem && sig && sem_value) {
        STEP("vkWaitSemaphores");
        VkSemaphoreWaitInfo wi = {
            .sType = VK_STRUCTURE_TYPE_SEMAPHORE_WAIT_INFO,
            .semaphoreCount = 1,
            .pSemaphores = sig,
            .pValues = sem_value,
        };
        r = vkWaitSemaphores_(g_device, &wi, timeout_ns);
        uint64_t t2 = now_us();
        if (r == VK_TIMEOUT) {
            ERR("%s: vkWaitSemaphores(value %" PRIu64 ") TIMED OUT after %.0f ms "
                "(the timeline syncobj point never materialised/signalled)",
                tag, *sem_value, MS(t2 - t1));
            why("vkWaitSemaphores timed out after %" PRIu64 " ms", g_timeout_ms);
            return WAIT_TIMEOUT;
        }
        if (r != VK_SUCCESS) {
            ERR("%s: vkWaitSemaphores -> %s after %.2f ms", tag, vk_result_str(r), MS(t2 - t1));
            why("vkWaitSemaphores -> %s", vk_result_str(r));
            if (r == VK_ERROR_DEVICE_LOST) g_device_lost = 1;
            return WAIT_ERROR;
        }
        INFO("%s: vkWaitSemaphores(value %" PRIu64 ") satisfied after %.2f ms",
             tag, *sem_value, MS(t2 - t1));
    }

    STEP("vkWaitForFences");
    r = vkWaitForFences_(g_device, 1, &g_fence, VK_TRUE, timeout_ns);
    uint64_t t2 = now_us();
    if (r == VK_TIMEOUT) {
        ERR("%s: vkWaitForFences TIMED OUT after %.0f ms (the fence never signalled: "
            "the pushbuffer did not execute, or its completion was never reported "
            "back through the syncobj)", tag, MS(t2 - t1));
        why("fence wait timed out after %" PRIu64 " ms", g_timeout_ms);
        return WAIT_TIMEOUT;
    }
    if (r != VK_SUCCESS) {
        ERR("%s: vkWaitForFences -> %s after %.2f ms", tag, vk_result_str(r), MS(t2 - t1));
        why("vkWaitForFences -> %s", vk_result_str(r));
        if (r == VK_ERROR_DEVICE_LOST) g_device_lost = 1;
        return WAIT_ERROR;
    }
    INFO("%s: fence signalled after %.2f ms (submit+wait %.2f ms)",
         tag, MS(t2 - t1), MS(t2 - t0));
    return WAIT_OK;
}

static result_t wait_to_result(wait_res w)
{
    return w == WAIT_TIMEOUT ? R_TIMEOUT : R_FAIL;
}

