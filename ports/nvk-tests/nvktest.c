static const uint8_t CLEAR_RGBA[4] = { 0x00, 0x00, 0xFF, 0xFF };
static const uint8_t TRI_RGBA[4]   = { 0xFF, 0x00, 0x00, 0xFF };

static char classify(const uint8_t *p)
{
    if (p[0] >= 0x80 && p[1] < 0x40 && p[2] < 0x40) return '#';
    if (p[0] < 0x40 && p[1] < 0x40 && p[2] >= 0x80) return '.';
    return '?';
}

static void print_ascii(const uint8_t *px)
{
    printf("nvktest img| +--------------------------------+  (32x16 samples of 256x256; "
           "# red, . clear, ? other)\n");
    for (uint32_t r = 0; r < 16; r++) {
        char line[33];
        for (uint32_t c = 0; c < 32; c++) {
            uint32_t x = c * 8 + 4, y = r * 16 + 8;
            line[c] = classify(px + ((size_t)y * IMG_W + x) * IMG_BPP);
        }
        line[32] = 0;
        printf("nvktest img| |%s|\n", line);
    }
    printf("nvktest img| +--------------------------------+\n");
}

static void write_ppm(const char *name, const uint8_t *px)
{
    char path[512];
    snprintf(path, sizeof(path), "%s/%s", g_out_dir, name);
    FILE *f = fopen(path, "wb");
    if (!f) { INFO("could not write %s: %s (not a test failure)", path, strerror(errno)); return; }
    fprintf(f, "P6\n%u %u\n255\n", IMG_W, IMG_H);
    int ok = 1;
    for (uint32_t i = 0; i < IMG_W * IMG_H && ok; i++)
        ok = fwrite(px + (size_t)i * 4, 1, 3, f) == 3;
    if (fclose(f) != 0) ok = 0;
    if (ok) INFO("wrote %s (P6 %ux%u)", path, IMG_W, IMG_H);
    else    INFO("writing %s failed: %s (not a test failure)", path, strerror(errno));
}

static void print_ppm32(const char *tag, const uint8_t *px)
{
    static const char b64[] =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    uint8_t buf[16 + 32 * 32 * 3];
    int hl = snprintf((char *)buf, 16, "P6\n32 32\n255\n");
    size_t n = (size_t)hl;
    for (uint32_t y = 0; y < 32; y++)
        for (uint32_t x = 0; x < 32; x++) {
            const uint8_t *p = px + ((size_t)(y * 8 + 4) * IMG_W + (x * 8 + 4)) * IMG_BPP;
            buf[n++] = p[0]; buf[n++] = p[1]; buf[n++] = p[2];
        }
    char out[((sizeof(buf) + 2) / 3) * 4 + 1];
    size_t o = 0;
    for (size_t i = 0; i < n; i += 3) {
        uint32_t v = (uint32_t)buf[i] << 16;
        if (i + 1 < n) v |= (uint32_t)buf[i + 1] << 8;
        if (i + 2 < n) v |= buf[i + 2];
        out[o++] = b64[(v >> 18) & 63];
        out[o++] = b64[(v >> 12) & 63];
        out[o++] = i + 1 < n ? b64[(v >> 6) & 63] : '=';
        out[o++] = i + 2 < n ? b64[v & 63] : '=';
    }
    out[o] = 0;
    printf("nvktest %s begin\n", tag);
    for (size_t i = 0; i < o; i += 76)
        printf("nvktest %s| %.*s\n", tag, (int)(o - i < 76 ? o - i : 76), out + i);
    printf("nvktest %s end\n", tag);
}

