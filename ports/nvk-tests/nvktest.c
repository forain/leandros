struct px_check { uint32_t x, y; const uint8_t *want; const char *label; };

static VkFormat pick_depth_format(void)
{
    static const VkFormat cands[] = {
        VK_FORMAT_D32_SFLOAT, VK_FORMAT_D24_UNORM_S8_UINT, VK_FORMAT_D32_SFLOAT_S8_UINT,
    };
    for (size_t i = 0; i < sizeof(cands) / sizeof(cands[0]); i++) {
        VkFormatProperties fp;
        memset(&fp, 0, sizeof(fp));
        vkGetPhysicalDeviceFormatProperties_(g_phys, cands[i], &fp);
        INFO("triangle_depth: format %d optimalTilingFeatures=0x%x", (int)cands[i],
             fp.optimalTilingFeatures);
        if (fp.optimalTilingFeatures & VK_FORMAT_FEATURE_DEPTH_STENCIL_ATTACHMENT_BIT)
            return cands[i];
    }
    return VK_FORMAT_UNDEFINED;
}

static const char *depth_fmt_name(VkFormat f)
{
    return f == VK_FORMAT_D32_SFLOAT ? "D32_SFLOAT" :
           f == VK_FORMAT_D24_UNORM_S8_UINT ? "D24_UNORM_S8_UINT" :
           f == VK_FORMAT_D32_SFLOAT_S8_UINT ? "D32_SFLOAT_S8_UINT" : "?";
}

static int create_image(const char *tag, VkFormat fmt, VkImageUsageFlags usage,
                        VkImageAspectFlags aspect, VkImage *img, VkDeviceMemory *mem,
                        VkImageView *view)
{
    VkImageCreateInfo ici = {
        .sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO,
        .imageType = VK_IMAGE_TYPE_2D,
        .format = fmt,
        .extent = { IMG_W, IMG_H, 1 },
        .mipLevels = 1, .arrayLayers = 1,
        .samples = VK_SAMPLE_COUNT_1_BIT,
        .tiling = VK_IMAGE_TILING_OPTIMAL,
        .usage = usage,
        .sharingMode = VK_SHARING_MODE_EXCLUSIVE,
        .initialLayout = VK_IMAGE_LAYOUT_UNDEFINED,
    };
    VkResult r = vkCreateImage_(g_device, &ici, NULL, img);
    if (r != VK_SUCCESS) {
        *img = VK_NULL_HANDLE;
        ERR("%s: vkCreateImage(format %d) -> %s", tag, (int)fmt, vk_result_str(r));
        why("%s: vkCreateImage -> %s", tag, vk_result_str(r));
        return 0;
    }
    VkMemoryRequirements req;
    vkGetImageMemoryRequirements_(g_device, *img, &req);
    INFO("%s: image size=%" PRIu64 " align=%" PRIu64 " memoryTypeBits=0x%08x",
         tag, (uint64_t)req.size, (uint64_t)req.alignment, req.memoryTypeBits);
    int32_t t = pick_kind(tag, req.memoryTypeBits, MEM_DEVICE);
    if (t < 0) { why("%s: no memory type for the image", tag); return 0; }
    VkMemoryAllocateInfo ai = {
        .sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO,
        .allocationSize = req.size, .memoryTypeIndex = (uint32_t)t,
    };
    r = vkAllocateMemory_(g_device, &ai, NULL, mem);
    if (r != VK_SUCCESS) {
        *mem = VK_NULL_HANDLE;
        ERR("%s: vkAllocateMemory(image) -> %s", tag, vk_result_str(r));
        why("%s: vkAllocateMemory(image) -> %s", tag, vk_result_str(r));
        return 0;
    }
    r = vkBindImageMemory_(g_device, *img, *mem, 0);
    if (r != VK_SUCCESS) {
        ERR("%s: vkBindImageMemory -> %s", tag, vk_result_str(r));
        why("%s: vkBindImageMemory -> %s", tag, vk_result_str(r));
        return 0;
    }
    VkImageViewCreateInfo ivci = {
        .sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO,
        .image = *img,
        .viewType = VK_IMAGE_VIEW_TYPE_2D,
        .format = fmt,
        .subresourceRange = { aspect, 0, 1, 0, 1 },
    };
    r = vkCreateImageView_(g_device, &ivci, NULL, view);
    if (r != VK_SUCCESS) {
        *view = VK_NULL_HANDLE;
        ERR("%s: vkCreateImageView -> %s", tag, vk_result_str(r));
        why("%s: vkCreateImageView -> %s", tag, vk_result_str(r));
        return 0;
    }
    return 1;
}

static result_t run_triangle(int with_depth)
{
    const char *tag = with_depth ? "triangle_depth" : "triangle";
    if (!(g_qflags & VK_QUEUE_GRAPHICS_BIT)) {
        why("chosen queue family has no VK_QUEUE_GRAPHICS_BIT");
        return R_SKIP;
    }
    VkFormat dfmt = VK_FORMAT_UNDEFINED;
    int depth_readback = 0;
    if (with_depth) {
        STEP("triangle_depth: pick depth format");
        dfmt = pick_depth_format();
        if (dfmt == VK_FORMAT_UNDEFINED) {
            why("no depth format with optimal-tiling DEPTH_STENCIL_ATTACHMENT");
            return R_SKIP;
        }
        VkFormatProperties fp;
        vkGetPhysicalDeviceFormatProperties_(g_phys, dfmt, &fp);
        depth_readback = (fp.optimalTilingFeatures & VK_FORMAT_FEATURE_TRANSFER_SRC_BIT) != 0;
        INFO("triangle_depth: using %s (depth readback %s)", depth_fmt_name(dfmt),
             depth_readback ? "enabled" : "unavailable: no TRANSFER_SRC");
    }
    VkImageAspectFlags daspect = VK_IMAGE_ASPECT_DEPTH_BIT;
    if (dfmt == VK_FORMAT_D24_UNORM_S8_UINT || dfmt == VK_FORMAT_D32_SFLOAT_S8_UINT)
        daspect |= VK_IMAGE_ASPECT_STENCIL_BIT;

    result_t res = R_FAIL;
    VkImage img = VK_NULL_HANDLE, dimg = VK_NULL_HANDLE;
    VkDeviceMemory imem = VK_NULL_HANDLE, dmem = VK_NULL_HANDLE;
    VkImageView view = VK_NULL_HANDLE, dview = VK_NULL_HANDLE;
    VkRenderPass rp = VK_NULL_HANDLE;
    VkFramebuffer fb = VK_NULL_HANDLE;
    VkShaderModule vmod = VK_NULL_HANDLE, fmod = VK_NULL_HANDLE;
    VkPipelineLayout play = VK_NULL_HANDLE;
    VkPipeline pipe = VK_NULL_HANDLE;
    nbuf host = {0};
    VkResult r;

    STEP("triangle: colour image");
    if (!create_image(tag, VK_FORMAT_R8G8B8A8_UNORM,
                      VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_TRANSFER_SRC_BIT,
                      VK_IMAGE_ASPECT_COLOR_BIT, &img, &imem, &view)) goto out;
    if (with_depth) {
        STEP("triangle_depth: depth image");
        if (!create_image("triangle_depth.z", dfmt,
                          VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT |
                          (depth_readback ? VK_IMAGE_USAGE_TRANSFER_SRC_BIT : 0),
                          daspect, &dimg, &dmem, &dview)) goto out;
    }
    STEP("triangle: readback buffer");
    if (nbuf_create(tag, &host, 2 * IMG_BYTES, VK_BUFFER_USAGE_TRANSFER_DST_BIT, MEM_HOST) != 1)
        goto out;

    VkAttachmentDescription att[2] = {
        {
            .format = VK_FORMAT_R8G8B8A8_UNORM,
            .samples = VK_SAMPLE_COUNT_1_BIT,
            .loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR,
            .storeOp = VK_ATTACHMENT_STORE_OP_STORE,
            .stencilLoadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE,
            .stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE,
            .initialLayout = VK_IMAGE_LAYOUT_UNDEFINED,
            .finalLayout = VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL,
        },
        {
            .format = dfmt,
            .samples = VK_SAMPLE_COUNT_1_BIT,
            .loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR,
            .storeOp = depth_readback ? VK_ATTACHMENT_STORE_OP_STORE : VK_ATTACHMENT_STORE_OP_DONT_CARE,
            .stencilLoadOp = VK_ATTACHMENT_LOAD_OP_CLEAR,
            .stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE,
            .initialLayout = VK_IMAGE_LAYOUT_UNDEFINED,
            .finalLayout = depth_readback ? VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL
                                          : VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL,
        },
    };
    VkAttachmentReference cref = { 0, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL };
    VkAttachmentReference dref = { 1, VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL };
    VkSubpassDescription sub = {
        .pipelineBindPoint = VK_PIPELINE_BIND_POINT_GRAPHICS,
        .colorAttachmentCount = 1,
        .pColorAttachments = &cref,
        .pDepthStencilAttachment = with_depth ? &dref : NULL,
    };
    VkSubpassDependency deps[2] = {
        {
            .srcSubpass = VK_SUBPASS_EXTERNAL, .dstSubpass = 0,
            .srcStageMask = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT |
                            VK_PIPELINE_STAGE_EARLY_FRAGMENT_TESTS_BIT,
            .dstStageMask = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT |
                            VK_PIPELINE_STAGE_EARLY_FRAGMENT_TESTS_BIT,
            .srcAccessMask = 0,
            .dstAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT |
                             VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT,
        },
        {
            .srcSubpass = 0, .dstSubpass = VK_SUBPASS_EXTERNAL,
            .srcStageMask = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT |
                            VK_PIPELINE_STAGE_LATE_FRAGMENT_TESTS_BIT,
            .dstStageMask = VK_PIPELINE_STAGE_TRANSFER_BIT,
            .srcAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT |
                             VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT,
            .dstAccessMask = VK_ACCESS_TRANSFER_READ_BIT,
        },
    };
    VkRenderPassCreateInfo rpci = {
        .sType = VK_STRUCTURE_TYPE_RENDER_PASS_CREATE_INFO,
        .attachmentCount = with_depth ? 2u : 1u, .pAttachments = att,
        .subpassCount = 1, .pSubpasses = &sub,
        .dependencyCount = 2, .pDependencies = deps,
    };
    STEP("triangle: vkCreateRenderPass");
    r = vkCreateRenderPass_(g_device, &rpci, NULL, &rp);
    if (r != VK_SUCCESS) { rp = VK_NULL_HANDLE; why("vkCreateRenderPass -> %s", vk_result_str(r)); goto out; }

    VkImageView fbviews[2] = { view, dview };
    VkFramebufferCreateInfo fbci = {
        .sType = VK_STRUCTURE_TYPE_FRAMEBUFFER_CREATE_INFO,
        .renderPass = rp,
        .attachmentCount = with_depth ? 2u : 1u, .pAttachments = fbviews,
        .width = IMG_W, .height = IMG_H, .layers = 1,
    };
    STEP("triangle: vkCreateFramebuffer");
    r = vkCreateFramebuffer_(g_device, &fbci, NULL, &fb);
    if (r != VK_SUCCESS) { fb = VK_NULL_HANDLE; why("vkCreateFramebuffer -> %s", vk_result_str(r)); goto out; }

    STEP("triangle: shader modules");
    vmod = make_module("triangle.vert", spv_tri_vert, sizeof(spv_tri_vert));
    if (!vmod) goto out;
    fmod = make_module("triangle.frag", spv_tri_frag, sizeof(spv_tri_frag));
    if (!fmod) goto out;

    VkPipelineLayoutCreateInfo plci = { .sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO };
    r = vkCreatePipelineLayout_(g_device, &plci, NULL, &play);
    if (r != VK_SUCCESS) { play = VK_NULL_HANDLE; why("vkCreatePipelineLayout -> %s", vk_result_str(r)); goto out; }

    VkPipelineShaderStageCreateInfo stages[2] = {
        { .sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO,
          .stage = VK_SHADER_STAGE_VERTEX_BIT, .module = vmod, .pName = "main" },
        { .sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO,
          .stage = VK_SHADER_STAGE_FRAGMENT_BIT, .module = fmod, .pName = "main" },
    };
    VkPipelineVertexInputStateCreateInfo vi = {
        .sType = VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO,
    };
    VkPipelineInputAssemblyStateCreateInfo ia = {
        .sType = VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO,
        .topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST,
    };
    VkViewport vp = { 0.0f, 0.0f, (float)IMG_W, (float)IMG_H, 0.0f, 1.0f };
    VkRect2D scissor = { { 0, 0 }, { IMG_W, IMG_H } };
    VkPipelineViewportStateCreateInfo vps = {
        .sType = VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO,
        .viewportCount = 1, .pViewports = &vp,
        .scissorCount = 1, .pScissors = &scissor,
    };
    VkPipelineRasterizationStateCreateInfo rs = {
        .sType = VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO,
        .polygonMode = VK_POLYGON_MODE_FILL,
        .cullMode = VK_CULL_MODE_NONE,
        .frontFace = VK_FRONT_FACE_COUNTER_CLOCKWISE,
        .lineWidth = 1.0f,
    };
    VkPipelineMultisampleStateCreateInfo ms = {
        .sType = VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO,
        .rasterizationSamples = VK_SAMPLE_COUNT_1_BIT,
    };
    VkPipelineDepthStencilStateCreateInfo ds = {
        .sType = VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO,
        .depthTestEnable = VK_TRUE,
        .depthWriteEnable = VK_TRUE,
        .depthCompareOp = VK_COMPARE_OP_LESS,
        .minDepthBounds = 0.0f,
        .maxDepthBounds = 1.0f,
    };
    VkPipelineColorBlendAttachmentState cba = {
        .blendEnable = VK_FALSE,
        .colorWriteMask = VK_COLOR_COMPONENT_R_BIT | VK_COLOR_COMPONENT_G_BIT |
                          VK_COLOR_COMPONENT_B_BIT | VK_COLOR_COMPONENT_A_BIT,
    };
    VkPipelineColorBlendStateCreateInfo cb = {
        .sType = VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO,
        .attachmentCount = 1, .pAttachments = &cba,
    };
    VkGraphicsPipelineCreateInfo gpci = {
        .sType = VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO,
        .stageCount = 2, .pStages = stages,
        .pVertexInputState = &vi,
        .pInputAssemblyState = &ia,
        .pViewportState = &vps,
        .pRasterizationState = &rs,
        .pMultisampleState = &ms,
        .pDepthStencilState = with_depth ? &ds : NULL,
        .pColorBlendState = &cb,
        .layout = play,
        .renderPass = rp,
        .subpass = 0,
    };
    STEP("triangle: vkCreateGraphicsPipelines (NAK compile)");
    uint64_t p0 = now_us();
    r = vkCreateGraphicsPipelines_(g_device, VK_NULL_HANDLE, 1, &gpci, NULL, &pipe);
    INFO("%s: vkCreateGraphicsPipelines -> %s in %.1f ms", tag, vk_result_str(r), MS(now_us() - p0));
    if (r != VK_SUCCESS) { pipe = VK_NULL_HANDLE; why("vkCreateGraphicsPipelines -> %s", vk_result_str(r)); goto out; }

    poison(&host);

    STEP("triangle: record");
    if (!begin_cb(tag)) goto out;
    VkClearValue clears[2];
    memset(clears, 0, sizeof(clears));
    clears[0].color.float32[2] = 1.0f;
    clears[0].color.float32[3] = 1.0f;
    clears[1].depthStencil.depth = 1.0f;
    clears[1].depthStencil.stencil = 0;
    VkRenderPassBeginInfo rpbi = {
        .sType = VK_STRUCTURE_TYPE_RENDER_PASS_BEGIN_INFO,
        .renderPass = rp,
        .framebuffer = fb,
        .renderArea = { { 0, 0 }, { IMG_W, IMG_H } },
        .clearValueCount = with_depth ? 2u : 1u,
        .pClearValues = clears,
    };
    vkCmdBeginRenderPass_(g_cb, &rpbi, VK_SUBPASS_CONTENTS_INLINE);
    vkCmdBindPipeline_(g_cb, VK_PIPELINE_BIND_POINT_GRAPHICS, pipe);
    vkCmdDraw_(g_cb, 3, 1, 0, 0);
    vkCmdEndRenderPass_(g_cb);
    VkBufferImageCopy bic = {
        .bufferOffset = 0,
        .imageSubresource = { VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1 },
        .imageExtent = { IMG_W, IMG_H, 1 },
    };
    vkCmdCopyImageToBuffer_(g_cb, img, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, host.buf, 1, &bic);
    if (depth_readback) {
        VkBufferImageCopy dbic = {
            .bufferOffset = IMG_BYTES,
            .imageSubresource = { VK_IMAGE_ASPECT_DEPTH_BIT, 0, 0, 1 },
            .imageExtent = { IMG_W, IMG_H, 1 },
        };
        vkCmdCopyImageToBuffer_(g_cb, dimg, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, host.buf, 1, &dbic);
    }
    host_read_barrier(VK_PIPELINE_STAGE_TRANSFER_BIT, VK_ACCESS_TRANSFER_WRITE_BIT);
    if (!end_cb(tag)) goto out;

    uint64_t t0 = now_us();
    wait_res w = submit_and_wait(tag, NULL, NULL, 0, NULL);
    if (w != WAIT_OK) { res = wait_to_result(w); goto out; }
    INFO("%s: render + readback elapsed %.2f ms", tag, MS(now_us() - t0));

    const uint8_t *px = (const uint8_t *)host.map;
    int fails = 0;
    char fwhy[256] = "";

    /* (a) named coordinates (see shaders/triangle.vert for the geometry). */
    static const struct px_check checks[] = {
        { 0,   0,   CLEAR_RGBA, "corner_top_left" },
        { 255, 0,   CLEAR_RGBA, "corner_top_right" },
        { 0,   255, CLEAR_RGBA, "corner_bottom_left" },
        { 255, 255, CLEAR_RGBA, "corner_bottom_right" },
        { 128, 10,  CLEAR_RGBA, "above_apex" },
        { 20,  100, CLEAR_RGBA, "left_of_edge" },
        { 240, 100, CLEAR_RGBA, "right_of_edge" },
        { 10,  240, CLEAR_RGBA, "below_base_left" },
        { 245, 240, CLEAR_RGBA, "below_base_right" },
        { 128, 160, TRI_RGBA,   "centroid" },
        { 128, 120, TRI_RGBA,   "inside_upper" },
        { 100, 200, TRI_RGBA,   "inside_lower_left" },
        { 160, 200, TRI_RGBA,   "inside_lower_right" },
    };
    int point_fail = 0;
    for (size_t i = 0; i < sizeof(checks) / sizeof(checks[0]); i++) {
        const struct px_check *c = &checks[i];
        const uint8_t *p = px + ((size_t)c->y * IMG_W + c->x) * IMG_BPP;
        if (memcmp(p, c->want, 4) != 0) {
            ERR("%s pixels: (%u,%u) %s: expected %02X %02X %02X %02X observed %02X %02X %02X %02X%s",
                tag, c->x, c->y, c->label,
                c->want[0], c->want[1], c->want[2], c->want[3], p[0], p[1], p[2], p[3],
                (p[0] == 0xA5 && p[1] == 0xA5 && p[2] == 0xA5 && p[3] == 0xA5)
                    ? "  <- CPU poison survived: the image copy never landed" : "");
            point_fail++;
        }
    }
    if (point_fail) { fails++; snprintf(fwhy + strlen(fwhy), sizeof(fwhy) - strlen(fwhy), " %d/13 named pixels wrong;", point_fail); }
    else INFO("%s pixels: all 13 named coordinates match", tag);

    /* (b) coverage vs analytic area, (c) intermediate colours. */
    uint32_t n_tri = 0, n_clear = 0, n_other = 0, ox = 0, oy = 0;
    uint8_t opx[4] = {0};
    for (uint32_t y = 0; y < IMG_H; y++)
        for (uint32_t x = 0; x < IMG_W; x++) {
            const uint8_t *p = px + ((size_t)y * IMG_W + x) * IMG_BPP;
            if (!memcmp(p, TRI_RGBA, 4)) n_tri++;
            else if (!memcmp(p, CLEAR_RGBA, 4)) n_clear++;
            else { if (!n_other) { ox = x; oy = y; memcpy(opx, p, 4); } n_other++; }
        }
    INFO("%s coverage: red=%u clear=%u other=%u (analytic red area %d +/- %d)",
         tag, n_tri, n_clear, n_other, TRI_AREA_PX, TRI_AREA_TOL);
    if (n_tri < (uint32_t)(TRI_AREA_PX - TRI_AREA_TOL) || n_tri > (uint32_t)(TRI_AREA_PX + TRI_AREA_TOL)) {
        fails++;
        snprintf(fwhy + strlen(fwhy), sizeof(fwhy) - strlen(fwhy), " red=%u not %d+/-%d;",
                 n_tri, TRI_AREA_PX, TRI_AREA_TOL);
    }
    if (n_other) {
        ERR("%s: %u pixels are neither colour; first at (%u,%u) = %02X %02X %02X %02X",
            tag, n_other, ox, oy, opx[0], opx[1], opx[2], opx[3]);
        fails++;
        snprintf(fwhy + strlen(fwhy), sizeof(fwhy) - strlen(fwhy), " %u other-colour pixels;", n_other);
    }

    uint32_t sum = fnv1a(px, IMG_BYTES);
    INFO("%s checksum: FNV-1a over %u bytes = 0x%08X", tag, IMG_BYTES, sum);

    /* (d) depth readback: 0.5 under the triangle, 1.0 (the clear) elsewhere,
     * and exactly as many 0.5 pixels as red pixels. */
    if (depth_readback) {
        const uint32_t *dz = (const uint32_t *)(px + IMG_BYTES);
        uint32_t n_half = 0, n_one = 0, n_dother = 0, mism = 0, fx = 0, fy = 0, fraw = 0;
        for (uint32_t y = 0; y < IMG_H; y++)
            for (uint32_t x = 0; x < IMG_W; x++) {
                uint32_t raw = dz[y * IMG_W + x];
                double d;
                if (dfmt == VK_FORMAT_D24_UNORM_S8_UINT) d = (double)(raw & 0xFFFFFFu) / 16777215.0;
                else { float f; memcpy(&f, &raw, 4); d = f; }
                int half = d > 0.499 && d < 0.501, one = d > 0.999 && d < 1.001;
                if (half) n_half++; else if (one) n_one++; else n_dother++;
                int red = !memcmp(px + ((size_t)y * IMG_W + x) * IMG_BPP, TRI_RGBA, 4);
                if ((red && !half) || (!red && !one)) {
                    if (!mism) { fx = x; fy = y; fraw = raw; }
                    mism++;
                }
            }
        INFO("%s depth: 0.5=%u 1.0=%u other=%u; colour/depth mismatches=%u",
             tag, n_half, n_one, n_dother, mism);
        if (mism) {
            ERR("%s depth: first mismatch at (%u,%u) raw=0x%08x (%s)", tag, fx, fy, fraw,
                fraw == POISON_PATTERN ? "CPU poison survived: depth copy never landed"
                                       : "depth value disagrees with the colour image");
            fails++;
            snprintf(fwhy + strlen(fwhy), sizeof(fwhy) - strlen(fwhy),
                     " %u depth texels disagree with colour;", mism);
        }
    }

    if (!with_depth) {
        g_triangle_sum = sum;
        write_ppm("nvktest-triangle.ppm", px);
        print_ascii(px);
        print_ppm32("ppm32", px);
    } else {
        write_ppm("nvktest-triangle-depth.ppm", px);
        print_ascii(px);
        if (g_triangle_sum && sum != g_triangle_sum) {
            INFO("triangle_depth: image differs from 'triangle' (0x%08X vs 0x%08X), "
                 "printing it too", sum, g_triangle_sum);
            print_ppm32("ppm32d", px);
        } else if (g_triangle_sum) {
            INFO("triangle_depth: image is byte-identical to 'triangle'");
        }
    }

    if (fails) { why("%s", fwhy[0] == ' ' ? fwhy + 1 : fwhy); res = R_FAIL; }
    else {
        why("red=%u px, FNV-1a 0x%08X%s%s", n_tri, sum,
            with_depth ? ", depth " : "", with_depth ? depth_fmt_name(dfmt) : "");
        res = R_PASS;
    }

out:
    if (res != R_TIMEOUT) {
        nbuf_destroy(&host);
        if (pipe)  vkDestroyPipeline_(g_device, pipe, NULL);
        if (play)  vkDestroyPipelineLayout_(g_device, play, NULL);
        if (fmod)  vkDestroyShaderModule_(g_device, fmod, NULL);
        if (vmod)  vkDestroyShaderModule_(g_device, vmod, NULL);
        if (fb)    vkDestroyFramebuffer_(g_device, fb, NULL);
        if (rp)    vkDestroyRenderPass_(g_device, rp, NULL);
        if (dview) vkDestroyImageView_(g_device, dview, NULL);
        if (dimg)  vkDestroyImage_(g_device, dimg, NULL);
        if (dmem)  vkFreeMemory_(g_device, dmem, NULL);
        if (view)  vkDestroyImageView_(g_device, view, NULL);
        if (img)   vkDestroyImage_(g_device, img, NULL);
        if (imem)  vkFreeMemory_(g_device, imem, NULL);
    }
    return res;
}

/* ────────────────────────── subtest: timestamps ────────────────────────── */

static result_t subtest_timestamps(void)
{
    if (g_ts_valid_bits == 0) {
        why("queue family %u has timestampValidBits=0", g_qfamily);
        return R_SKIP;
    }
    result_t res = R_FAIL;
    VkQueryPool qp = VK_NULL_HANDLE;
    nbuf dev = {0};
    VkQueryPoolCreateInfo qpci = {
        .sType = VK_STRUCTURE_TYPE_QUERY_POOL_CREATE_INFO,
        .queryType = VK_QUERY_TYPE_TIMESTAMP,
        .queryCount = 2,
    };
    STEP("timestamps: vkCreateQueryPool");
    VkResult r = vkCreateQueryPool_(g_device, &qpci, NULL, &qp);
    if (r != VK_SUCCESS) { qp = VK_NULL_HANDLE; why("vkCreateQueryPool -> %s", vk_result_str(r)); goto out; }
    STEP("timestamps: buffer");
    if (nbuf_create("timestamps.dev", &dev, TS_FILL_BYTES, VK_BUFFER_USAGE_TRANSFER_DST_BIT,
                    MEM_DEVICE) != 1) goto out;
    if (!begin_cb("timestamps")) goto out;
    vkCmdResetQueryPool_(g_cb, qp, 0, 2);
    vkCmdWriteTimestamp_(g_cb, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, qp, 0);
    vkCmdFillBuffer_(g_cb, dev.buf, 0, TS_FILL_BYTES, 0x12345678u);
    vkCmdWriteTimestamp_(g_cb, VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT, qp, 1);
    if (!end_cb("timestamps")) goto out;
    wait_res w = submit_and_wait("timestamps", NULL, NULL, 0, NULL);
    if (w != WAIT_OK) { res = wait_to_result(w); goto out; }
    uint64_t ts[2] = { 0, 0 };
    STEP("timestamps: vkGetQueryPoolResults");
    r = vkGetQueryPoolResults_(g_device, qp, 0, 2, sizeof(ts), ts, sizeof(uint64_t),
                               VK_QUERY_RESULT_64_BIT);
    if (r != VK_SUCCESS) { why("vkGetQueryPoolResults -> %s", vk_result_str(r)); goto out; }
    uint64_t mask = g_ts_valid_bits >= 64 ? ~0ull : ((1ull << g_ts_valid_bits) - 1);
    uint64_t t0 = ts[0] & mask, t1 = ts[1] & mask;
    uint64_t dt = (t1 - t0) & mask;
    double ns = (double)dt * (double)g_props.limits.timestampPeriod;
    INFO("timestamps: t0=%" PRIu64 " t1=%" PRIu64 " delta=%" PRIu64 " ticks = %.0f ns "
         "for a %u MiB fill (%.2f GB/s)", t0, t1, dt, ns, TS_FILL_BYTES >> 20,
         ns > 0 ? (double)TS_FILL_BYTES / ns : 0.0);
    if (t0 == 0 && t1 == 0) { why("both timestamps are zero"); goto out; }
    if (t1 < t0 && dt > mask / 2) { why("t1 < t0 (t0=%" PRIu64 ", t1=%" PRIu64 ")", t0, t1); goto out; }
    why("%.0f ns for a %u MiB fill", ns, TS_FILL_BYTES >> 20);
    res = R_PASS;
out:
    if (res != R_TIMEOUT) {
        nbuf_destroy(&dev);
        if (qp) vkDestroyQueryPool_(g_device, qp, NULL);
    }
    return res;
}

/* ────────────────────────── main ────────────────────────── */

static const char *const SUBTESTS[] = {
    "info", "fill", "timeline", "compute", "triangle", "triangle_depth", "timestamps",
};
#define N_SUBTESTS (sizeof(SUBTESTS) / sizeof(SUBTESTS[0]))

static void usage(void)
{
    printf(
        "usage: nvktest [options] [subtest ...]\n"
        "  --icd PATH | --icd=PATH  Vulkan ICD to dlopen (default " DEFAULT_ICD ")\n"
        "  --timeout-ms=N           fence/semaphore wait timeout (default %llu)\n"
        "  --watchdog-s=N           SIGALRM watchdog per subtest (default 3*timeout+30 s)\n"
        "  --only=a,b,c             run only these subtests (same as positional names)\n"
        "  --out-dir=DIR            where nvktest-triangle.ppm goes (default " DEFAULT_OUT_DIR ")\n"
        "  -h, --help               this text\n"
        "subtests (in order): info fill timeline compute triangle triangle_depth timestamps\n"
        "('info' always runs: it picks the device)\n"
        "exit: failures (max 120), 126 after a timeout, 3 with zero physical devices\n",
        DEFAULT_TIMEOUT_MS);
}

static int select_name(int *sel, const char *name, size_t len)
{
    for (size_t i = 0; i < N_SUBTESTS; i++)
        if (strlen(SUBTESTS[i]) == len && !strncmp(SUBTESTS[i], name, len)) { sel[i] = 1; return 1; }
    printf("nvktest: unknown subtest '%.*s'\n", (int)len, name);
    return 0;
}

static void print_env(const char *name)
{
    const char *v = getenv(name);
    printf("[ENV ] %s=%s\n", name, v ? v : "(unset)");
}

int main(int argc, char **argv)
{
    setvbuf(stdout, NULL, _IOLBF, 0);

    int sel[N_SUBTESTS] = {0}, any_sel = 0;
    unsigned watchdog_override = 0;
    for (int i = 1; i < argc; i++) {
        const char *a = argv[i];
        if (!strcmp(a, "--icd") && i + 1 < argc) g_icd_path = argv[++i];
        else if (!strncmp(a, "--icd=", 6)) g_icd_path = a + 6;
        else if (!strncmp(a, "--timeout-ms=", 13)) g_timeout_ms = strtoull(a + 13, NULL, 0);
        else if (!strncmp(a, "--watchdog-s=", 13)) watchdog_override = (unsigned)strtoul(a + 13, NULL, 0);
        else if (!strncmp(a, "--out-dir=", 10)) g_out_dir = a + 10;
        else if (!strncmp(a, "--only=", 7)) {
            const char *p = a + 7;
            while (*p) {
                const char *c = strchr(p, ',');
                size_t len = c ? (size_t)(c - p) : strlen(p);
                if (len && !select_name(sel, p, len)) { usage(); return 2; }
                any_sel = 1;
                p += len + (c ? 1 : 0);
            }
        }
        else if (!strcmp(a, "-h") || !strcmp(a, "--help")) { usage(); return 0; }
        else if (a[0] != '-') {
            if (!select_name(sel, a, strlen(a))) { usage(); return 2; }
            any_sel = 1;
        }
        else { printf("nvktest: unknown option '%s'\n", a); usage(); return 2; }
    }
    if (!any_sel) for (size_t i = 0; i < N_SUBTESTS; i++) sel[i] = 1;
    sel[0] = 1;  /* info always runs */
    if (g_timeout_ms == 0) g_timeout_ms = DEFAULT_TIMEOUT_MS;
    g_watchdog_s = watchdog_override ? watchdog_override
                                     : (unsigned)(g_timeout_ms * 3 / 1000) + 30;

    install_signals();

    printf("==== nvktest: NVK (nouveau Vulkan) bring-up test ====\n");
    printf("[INFO] icd=%s timeout=%" PRIu64 " ms watchdog=%u s out-dir=%s\n",
           g_icd_path, g_timeout_ms, g_watchdog_s, g_out_dir);
    printf("[INFO] subtests:");
    for (size_t i = 0; i < N_SUBTESTS; i++) if (sel[i]) printf(" %s", SUBTESTS[i]);
    printf("\n");
    print_env("VK_ICD_FILENAMES");
    print_env("NVK_DEBUG");
    print_env("NAK_DEBUG");
    print_env("MESA_SHADER_CACHE_DISABLE");
    print_env("MESA_DEBUG");
    print_env("MESA_LOG_LEVEL");
    g_cur = "preflight";
    watchdog_arm();
    preflight();
    watchdog_off();
    fflush(stdout);

    /* ── init + info ── */
    g_cur = "init";
    watchdog_arm();
    if (!bootstrap_instance()) {
        watchdog_off();
        report("init", R_FAIL);
        print_done();
        return g_fail > 120 ? 120 : g_fail;
    }
    g_cur = "info";
    result_t ri = subtest_info();
    watchdog_off();
    if (ri == R_SKIP) {
        printf("nvktest info: 0 physical devices (no nouveau DRM device)\n");
        if (vkDestroyInstance_) vkDestroyInstance_(g_instance, NULL);
        print_done();
        return 3;
    }
    report("info", ri);
    if (ri != R_PASS) {
        if (vkDestroyInstance_) vkDestroyInstance_(g_instance, NULL);
        print_done();
        return g_fail > 120 ? 120 : g_fail;
    }

    g_cur = "device";
    watchdog_arm();
    result_t rd = create_device();
    watchdog_off();
    report("device", rd);

    for (size_t i = 1; i < N_SUBTESTS; i++) {
        if (!sel[i]) continue;
        g_cur = SUBTESTS[i];
        if (rd != R_PASS) { why("no usable device"); report(SUBTESTS[i], R_SKIP); continue; }
        if (g_timeout) { why("an earlier subtest timed out"); report(SUBTESTS[i], R_SKIP); continue; }
        if (g_device_lost) { why("device lost earlier"); report(SUBTESTS[i], R_SKIP); continue; }
        printf("\n[STEP] %s\n", SUBTESTS[i]);
        uint64_t t0 = now_us();
        watchdog_arm();
        result_t r;
        switch (i) {
        case 1: r = subtest_fill(); break;
        case 2: r = subtest_timeline(); break;
        case 3: r = subtest_compute(); break;
        case 4: r = run_triangle(0); break;
        case 5: r = run_triangle(1); break;
        default: r = subtest_timestamps(); break;
        }
        watchdog_off();
        INFO("%s: subtest took %.1f ms", SUBTESTS[i], MS(now_us() - t0));
        report(SUBTESTS[i], r);
    }

    if (g_timeout) {
        printf("[ERR ] a wait TIMED OUT - teardown deliberately SKIPPED (destroying objects "
               "under a live submission would turn a diagnosable hang into a crash)\n");
        print_done();
        return 126;
    }

    g_cur = "teardown";
    watchdog_arm();
    if (g_device) {
        STEP("vkDeviceWaitIdle");
        if (vkDeviceWaitIdle_ && !g_device_lost) vkDeviceWaitIdle_(g_device);
        STEP("destroy device objects");
        if (g_fence && vkDestroyFence_) vkDestroyFence_(g_device, g_fence, NULL);
        if (g_cb && vkFreeCommandBuffers_) vkFreeCommandBuffers_(g_device, g_pool, 1, &g_cb);
        if (g_pool && vkDestroyCommandPool_) vkDestroyCommandPool_(g_device, g_pool, NULL);
        STEP("vkDestroyDevice");
        vkDestroyDevice_(g_device, NULL);
        g_device = VK_NULL_HANDLE;
    }
    STEP("vkDestroyInstance");
    if (g_instance && vkDestroyInstance_) vkDestroyInstance_(g_instance, NULL);
    watchdog_off();
    INFO("teardown complete");

    print_done();
    return g_fail > 120 ? 120 : g_fail;
}
