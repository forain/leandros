/* nvktest — boot-time NVK (Mesa nouveau Vulkan) bring-up test for LeandrOS.
 *
 * Derived from vkrender (leandros-artifacts/venus-lane/vkrender.c), the Venus
 * GPU submission test: same loader-less design, same reporting idiom, same
 * rule that every wait is finite and that nothing is torn down after a
 * timeout. It targets a real NVIDIA GPU driven by Mesa's NVK through the
 * kernel's nouveau-UAPI translation layer, and it is meant to run unattended
 * at boot (/bin/nvk-autotest) with its stdout persisted to a log the user
 * reads afterwards. So:
 *
 *   - the output is the product: every failing call names its VkResult, every
 *     subtest ends in exactly one line
 *         nvktest <name>: PASS|FAIL|TIMEOUT|SKIP (<why>)
 *     and the run ends in
 *         ==== nvktest done: P passed, F failed, S skipped, T timeout ====
 *   - it must never hang: fence/semaphore waits use --timeout-ms, and a
 *     SIGALRM watchdog covers calls that have no timeout of their own (an
 *     ioctl that blocks inside the driver). Fatal signals are caught too, so
 *     a crash still produces a subtest line and the final summary.
 *
 * No Khronos loader: the ICD is dlopen()ed by absolute path and bootstrapped
 * through vk_icdGetInstanceProcAddr, then device-level entry points come from
 * vkGetDeviceProcAddr.
 *
 * Subtests (in order; `info` always runs because it picks the device):
 *   info            enumerate + describe the physical device(s)
 *   fill            shaderless: vkCmdFillBuffer into VRAM + copy to sysmem,
 *                   fill sysmem directly, fill a CPU-mapped VRAM (BAR) buffer
 *   timeline        timeline semaphore signalled by a submit, waited on by
 *                   vkWaitSemaphores, then host-signalled (DRM timeline syncobjs)
 *   compute         C = A + B storage-buffer shader, host memory, then VRAM
 *   triangle        clear + red triangle into an OPTIMAL R8G8B8A8 image
 *   triangle_depth  same triangle with a depth attachment (depth PTE kinds),
 *                   depth readback verified too
 *   timestamps      two timestamps around a fill (non-essential)
 *
 * Exit code: number of failures (clamped to 120), 126 after a timeout, 3 when
 * the ICD enumerates zero physical devices (the expected result in QEMU).
 */

