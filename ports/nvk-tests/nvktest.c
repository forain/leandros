typedef enum { MEM_HOST = 0, MEM_DEVICE, MEM_DEVICE_HOST } memkind_t;
static const char *const memkind_names[] = {
    "HOST(sysmem, HV|HC)", "DEVICE(VRAM)", "DEVICE+HOST(VRAM via BAR)"
};

/* Three passes: required+preferred without forbidden, required without
 * forbidden, then (unless strict) required alone. Always logged. */
static int32_t pick_memory_type(const char *tag, uint32_t type_bits,
                                VkMemoryPropertyFlags required,
                                VkMemoryPropertyFlags preferred,
                                VkMemoryPropertyFlags forbidden, int strict)
{
    char fb[160];
    for (int pass = 0; pass < (strict ? 2 : 3); pass++) {
        for (uint32_t i = 0; i < g_mem_props.memoryTypeCount; i++) {
            if (!(type_bits & (1u << i))) continue;
            VkMemoryPropertyFlags f = g_mem_props.memoryTypes[i].propertyFlags;
            if ((f & required) != required) continue;
            if (pass < 2 && (f & forbidden)) continue;
            if (pass == 0 && (f & preferred) != preferred) continue;
            mem_flags_str(f, fb, sizeof(fb));
            INFO("%s: picked memory type %u (heap %u) flags=0x%x [%s] (pass %d)",
                 tag, i, g_mem_props.memoryTypes[i].heapIndex, f, fb, pass);
            return (int32_t)i;
        }
    }
    if (!strict)
        ERR("%s: no memory type in mask 0x%08x satisfies required=0x%x",
            tag, type_bits, required);
    return -1;
}

static int32_t pick_kind(const char *tag, uint32_t bits, memkind_t k)
{
    switch (k) {
    case MEM_HOST:
        return pick_memory_type(tag, bits,
            VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT,
            VK_MEMORY_PROPERTY_HOST_CACHED_BIT, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT, 0);
    case MEM_DEVICE:
        return pick_memory_type(tag, bits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT, 0,
                                VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT, 0);
    case MEM_DEVICE_HOST:
        return pick_memory_type(tag, bits,
            VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT | VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT |
            VK_MEMORY_PROPERTY_HOST_COHERENT_BIT, 0, 0, 1);
    }
    return -1;
}

typedef struct {
    VkBuffer buf;
    VkDeviceMemory mem;
    void *map;
    VkDeviceSize size;
} nbuf;

static void nbuf_destroy(nbuf *b)
{
    if (!g_device) return;
    if (b->map) vkUnmapMemory_(g_device, b->mem);
    if (b->buf) vkDestroyBuffer_(g_device, b->buf, NULL);
    if (b->mem) vkFreeMemory_(g_device, b->mem, NULL);
    memset(b, 0, sizeof(*b));
}

/* Returns 1 on success, 0 on failure (why() set), -1 when kind is
 * MEM_DEVICE_HOST and no such memory type exists. */
static int nbuf_create(const char *tag, nbuf *b, VkDeviceSize size,
                       VkBufferUsageFlags usage, memkind_t kind)
{
    memset(b, 0, sizeof(*b));
    b->size = size;
    VkBufferCreateInfo bi = {
        .sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO,
        .size = size,
        .usage = usage,
        .sharingMode = VK_SHARING_MODE_EXCLUSIVE,
    };
    VkResult r = vkCreateBuffer_(g_device, &bi, NULL, &b->buf);
    if (r != VK_SUCCESS) {
        ERR("%s: vkCreateBuffer(%" PRIu64 " bytes) -> %s", tag, (uint64_t)size, vk_result_str(r));
        why("%s: vkCreateBuffer -> %s", tag, vk_result_str(r));
        return 0;
    }
    VkMemoryRequirements req;
    vkGetBufferMemoryRequirements_(g_device, b->buf, &req);
    INFO("%s: %s buffer size=%" PRIu64 " req.size=%" PRIu64 " align=%" PRIu64
         " memoryTypeBits=0x%08x", tag, memkind_names[kind], (uint64_t)size,
         (uint64_t)req.size, (uint64_t)req.alignment, req.memoryTypeBits);
    int32_t t = pick_kind(tag, req.memoryTypeBits, kind);
    if (t < 0) {
        if (kind == MEM_DEVICE_HOST) { nbuf_destroy(b); return -1; }
        why("%s: no suitable memory type (bits 0x%08x)", tag, req.memoryTypeBits);
        nbuf_destroy(b);
        return 0;
    }
    VkMemoryAllocateInfo ai = {
        .sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO,
        .allocationSize = req.size,
        .memoryTypeIndex = (uint32_t)t,
    };
    r = vkAllocateMemory_(g_device, &ai, NULL, &b->mem);
    if (r != VK_SUCCESS) {
        ERR("%s: vkAllocateMemory(%" PRIu64 " bytes, type %d) -> %s",
            tag, (uint64_t)req.size, t, vk_result_str(r));
        why("%s: vkAllocateMemory(type %d) -> %s", tag, t, vk_result_str(r));
        nbuf_destroy(b);
        return 0;
    }
    r = vkBindBufferMemory_(g_device, b->buf, b->mem, 0);
    if (r != VK_SUCCESS) {
        ERR("%s: vkBindBufferMemory -> %s", tag, vk_result_str(r));
        why("%s: vkBindBufferMemory -> %s", tag, vk_result_str(r));
        nbuf_destroy(b);
        return 0;
    }
    if (g_mem_props.memoryTypes[t].propertyFlags & VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT) {
        uint64_t m0 = now_us();
        r = vkMapMemory_(g_device, b->mem, 0, VK_WHOLE_SIZE, 0, &b->map);
        if (r != VK_SUCCESS || !b->map) {
            ERR("%s: vkMapMemory -> %s (ptr %p)", tag, vk_result_str(r), b->map);
            why("%s: vkMapMemory -> %s", tag, vk_result_str(r));
            b->map = NULL;
            nbuf_destroy(b);
            return 0;
        }
        INFO("%s: mapped at %p in %.2f ms", tag, b->map, MS(now_us() - m0));
        /* Prove the mapping is real CPU-writable memory before any GPU work. */
        volatile uint32_t *w = (volatile uint32_t *)b->map;
        size_t last = (size_t)(size / 4) - 1;
        w[0] = POISON_PATTERN; w[last] = POISON_PATTERN;
        if (w[0] != POISON_PATTERN || w[last] != POISON_PATTERN) {
            ERR("%s: CPU write/readback through the mapping failed: "
                "word[0]=0x%08x word[last]=0x%08x", tag, w[0], w[last]);
            why("%s: mapping is not CPU read/writable", tag);
            nbuf_destroy(b);
            return 0;
        }
    }
    return 1;
}

static void poison(nbuf *b)
{
    uint32_t *w = (uint32_t *)b->map;
    for (size_t i = 0; i < b->size / 4; i++) w[i] = POISON_PATTERN;
}

/* Verify every word of a mapped buffer against a constant; logs the first
 * mismatch with an interpretation. Returns the number of bad words. */
static uint32_t verify_const(const char *tag, const nbuf *b, uint32_t want)
{
    const volatile uint32_t *w = (const volatile uint32_t *)b->map;
    uint32_t n = (uint32_t)(b->size / 4), bad = 0, fi = 0, fv = 0;
    for (uint32_t i = 0; i < n; i++) {
        uint32_t v = w[i];
        if (v != want) { if (!bad) { fi = i; fv = v; } bad++; }
    }
    if (bad)
        ERR("%s: %u/%u words wrong; first at index %u: expected 0x%08x observed 0x%08x (%s)",
            tag, bad, n, fi, want, fv,
            fv == POISON_PATTERN ? "CPU poison survived: no GPU write reached this memory"
            : fv == 0 ? "zeros: memory was cleared but never written"
            : "neither the pattern nor the poison: something wrote garbage");
    else
        INFO("%s: all %u words == 0x%08x", tag, n, want);
    return bad;
}

