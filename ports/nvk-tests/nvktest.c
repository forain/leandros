/* ────────────────────────── reporting ────────────────────────── */

static int g_pass = 0, g_fail = 0, g_skip = 0, g_tmo = 0;
static int g_timeout = 0;       /* a wait timed out: no teardown from here on */
static int g_device_lost = 0;

/* For the signal handlers: plain pointers to string literals only. */
static const char *volatile g_cur  = "startup";   /* current subtest */
static const char *volatile g_step = "startup";   /* current step inside it */
static unsigned g_watchdog_s = 0;

#define INFO(fmt, ...) do { printf("[INFO] " fmt "\n", ##__VA_ARGS__); } while (0)
#define WARN(fmt, ...) do { printf("[WARN] " fmt "\n", ##__VA_ARGS__); } while (0)
#define ERR(fmt, ...)  do { printf("[ERR ] " fmt "\n", ##__VA_ARGS__); } while (0)
#define STEP(s) (g_step = (s))

typedef enum { R_PASS = 0, R_FAIL, R_SKIP, R_TIMEOUT } result_t;

static char g_why[512];

static void why(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
static void why(const char *fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(g_why, sizeof(g_why), fmt, ap);
    va_end(ap);
}

/* Every result line, kept for the recap printed right before the "done"
 * line: on the PC the person reads the monitor (the console is the screen),
 * where the [INFO] lines scroll each result away; the recap puts all of them
 * on the last screenful. Plain static buffers, so the signal handlers can
 * print them with write(2) too. */
#define RECAP_MAX 16
static char g_recap[RECAP_MAX][160];
static volatile int g_recap_n = 0;

static void recap_add(const char *line)
{
    if (g_recap_n >= RECAP_MAX) return;
    snprintf(g_recap[g_recap_n], sizeof(g_recap[0]), "%s", line);
    g_recap_n++;
}

static void report(const char *name, result_t r)
{
    static const char *const names[] = { "PASS", "FAIL", "SKIP", "TIMEOUT" };
    char line[sizeof(g_recap[0])];
    if (g_why[0]) printf("nvktest %s: %s (%s)\n", name, names[r], g_why);
    else          printf("nvktest %s: %s\n", name, names[r]);
    /* The recap keeps each line short enough for one screen row. */
    if (g_why[0]) snprintf(line, sizeof(line), "nvktest %s: %s (%.100s)", name, names[r], g_why);
    else          snprintf(line, sizeof(line), "nvktest %s: %s", name, names[r]);
    recap_add(line);
    switch (r) {
    case R_PASS: g_pass++; break;
    case R_FAIL: g_fail++; break;
    case R_SKIP: g_skip++; break;
    case R_TIMEOUT: g_tmo++; g_timeout = 1; break;
    }
    g_why[0] = 0;
    fflush(stdout);
}

static void print_recap(void)
{
    if (g_recap_n == 0) return;
    printf("---- nvktest summary ----\n");
    for (int i = 0; i < g_recap_n; i++) printf("  %s\n", g_recap[i]);
}

static void print_done(void)
{
    print_recap();
    printf("==== nvktest done: %d passed, %d failed, %d skipped, %d timeout ====\n",
           g_pass, g_fail, g_skip, g_tmo);
    fflush(stdout);
}

/* ── async-signal-safe last words ── */

static void sig_puts(const char *s) { if (s) (void)!write(1, s, strlen(s)); }
static void sig_putu(unsigned v)
{
    char b[16]; int i = (int)sizeof(b);
    b[--i] = 0;
    do { b[--i] = (char)('0' + v % 10); v /= 10; } while (v && i > 0);
    sig_puts(&b[i]);
}
static void sig_done(int fail, int tmo)
{
    int n = g_recap_n;
    if (n > 0) {
        sig_puts("---- nvktest summary (before the TIMEOUT/FAIL line above) ----\n");
        for (int i = 0; i < n && i < RECAP_MAX; i++) { sig_puts("  "); sig_puts(g_recap[i]); sig_puts("\n"); }
    }
    sig_puts("==== nvktest done: "); sig_putu((unsigned)g_pass);
    sig_puts(" passed, "); sig_putu((unsigned)fail);
    sig_puts(" failed, "); sig_putu((unsigned)g_skip);
    sig_puts(" skipped, "); sig_putu((unsigned)tmo);
    sig_puts(" timeout ====\n");
}

static void on_alarm(int sig)
{
    (void)sig;
    sig_puts("\nnvktest "); sig_puts(g_cur);
    sig_puts(": TIMEOUT (watchdog: no progress for "); sig_putu(g_watchdog_s);
    sig_puts(" s in step '"); sig_puts(g_step);
    sig_puts("' - a driver call or ioctl blocked without a timeout; teardown skipped)\n");
    sig_done(g_fail, g_tmo + 1);
    _exit(126);
}

static void on_fatal(int sig)
{
    const char *n = sig == SIGSEGV ? "SIGSEGV" : sig == SIGBUS ? "SIGBUS" :
                    sig == SIGILL ? "SIGILL" : sig == SIGFPE ? "SIGFPE" :
                    sig == SIGABRT ? "SIGABRT" : "signal";
    sig_puts("\nnvktest "); sig_puts(g_cur);
    sig_puts(": FAIL (crashed with "); sig_puts(n); sig_puts(" ("); sig_putu((unsigned)sig);
    sig_puts(") in step '"); sig_puts(g_step); sig_puts("')\n");
    sig_done(g_fail + 1, g_tmo);
    int rc = g_fail + 1;
    _exit(rc > 120 ? 120 : rc);
}

static void install_signals(void)
{
    struct sigaction sa;
    memset(&sa, 0, sizeof(sa));
    sa.sa_handler = on_alarm;
    sigaction(SIGALRM, &sa, NULL);
    sa.sa_handler = on_fatal;
    sa.sa_flags = SA_RESETHAND;
    sigaction(SIGSEGV, &sa, NULL);
    sigaction(SIGBUS, &sa, NULL);
    sigaction(SIGILL, &sa, NULL);
    sigaction(SIGFPE, &sa, NULL);
    sigaction(SIGABRT, &sa, NULL);
}

static void watchdog_arm(void) { alarm(g_watchdog_s); }
static void watchdog_off(void) { alarm(0); }

