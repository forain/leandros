//! Host tests: FAT32 images from mkfs.fat + mcopy shaped like the card's p1,
//! power-loss replay at every sector write, gates, dry-runs, secrecy.
use super::*;
use std::cell::RefCell;
use std::process::Command;
use std::rc::Rc;

const PSK: &str = "SUPERSECRETPSK9";
type Img = Rc<RefCell<Vec<u8>>>;
type Log = Rc<RefCell<Vec<(u64, Vec<u8>)>>>;

#[derive(Clone)]
struct Mem {
    img: Img,
    log: Log,
}
impl Disk for Mem {
    fn read(&mut self, lba: u64, buf: &mut [u8]) -> R<()> {
        let i = self.img.borrow();
        buf.copy_from_slice(&i[lba as usize * SS..lba as usize * SS + buf.len()]);
        Ok(())
    }
    fn write(&mut self, lba: u64, data: &[u8]) -> R<()> {
        for (k, c) in data.chunks(SS).enumerate() {
            self.img.borrow_mut()[(lba as usize + k) * SS..(lba as usize + k + 1) * SS].copy_from_slice(c);
            self.log.borrow_mut().push((lba + k as u64, c.to_vec()));
        }
        Ok(())
    }
}

struct TSys {
    words: Vec<&'static str>,
    tag: String,
    good_initrd: Vec<u8>,
    held: RefCell<u32>,
    confirmed: RefCell<u32>,
    tried: RefCell<u32>,
}
impl Sys for TSys {
    fn has_word(&self, w: &str) -> bool {
        self.words.contains(&w)
    }
    fn tag(&self) -> String {
        format!("#1 {}", self.tag)
    }
    fn hold(&self) -> R<()> {
        *self.held.borrow_mut() += 1;
        Ok(())
    }
    fn confirm(&self) -> R<()> {
        *self.confirmed.borrow_mut() += 1;
        Ok(())
    }
    fn reboot_try(&self) -> R<()> {
        *self.tried.borrow_mut() += 1;
        Ok(())
    }
    fn reboot_plain(&self) -> R<()> {
        Ok(())
    }
    fn good_initrd(&self) -> R<Vec<u8>> {
        Ok(self.good_initrd.clone())
    }
    fn now(&self) -> String {
        String::new()
    }
}
fn sys(words: &[&'static str], tag: &str, initrd: &[u8]) -> TSys {
    TSys { words: words.to_vec(), tag: tag.into(), good_initrd: initrd.to_vec(), held: 0.into(), confirmed: 0.into(), tried: 0.into() }
}

fn rnd(seed: u64, n: usize) -> Vec<u8> {
    let mut s = seed.wrapping_mul(0x9E37_79B9_7F4A_7C15) | 1;
    (0..n).map(|_| { s ^= s << 13; s ^= s >> 7; s ^= s << 17; (s >> 24) as u8 }).collect()
}

/// A realistic ~2.6 KB config.txt: the four essentials in sector 0 among
/// comments, plus more comment and non-essential lines later.
fn config_txt() -> Vec<u8> {
    let mut s = String::new();
    s += "# LeandrOS Raspberry Pi 5 boot configuration\n# generated by prepare-rpi5-sdcard.sh\n\n";
    s += "arm_64bit=1\n# kernel image (flat binary) loaded at 0x200000\nkernel=kernel.img\nkernel_address=0x200000\n";
    s += "# initial ramdisk loaded high\ninitramfs initrd.cpio 0x10000000\n";
    s += "# ---- video ----\nframebuffer_depth=32\n";
    let mut i = 0;
    while s.len() < 2600 {
        s += &format!("# comment line {:02} -- padding text that mimics the long explanatory comments of the real file\n", i);
        i += 1;
        if i == 14 {
            s += "enable_uart=1\n";
        }
    }
    let mut b = s.into_bytes();
    b.truncate(2648);
    if let Some(p) = b.iter().rposition(|&c| c == b'\n') {
        b.truncate(p + 1);
    }
    b
}
fn cmdline() -> Vec<u8> {
    format!("root=LABEL=leandros-root console=ttyAMA10,115200 wifi.ssid=lab wifi.psk={}\n", PSK).into_bytes()
}

struct Card {
    img: Img,
    log: Log,
    kernel: Vec<u8>,
    initrd: Vec<u8>,
}
fn tmp(n: &str) -> std::path::PathBuf {
    let d = std::env::temp_dir().join(format!("pitest-{}-{:?}", std::process::id(), std::thread::current().id()).replace("ThreadId(", "t").replace(')', ""));
    std::fs::create_dir_all(&d).unwrap();
    d.join(n)
}
fn mk_card(fill_root: usize) -> Card {
    mk_card_g(fill_root, false)
}
/// The real Pi card geometry: FAT32, 512 B sectors, 8 spc, 32 reserved, 2 x 975
/// FAT sectors, data at sector 1982 (mod 8 = 6), 1,000,000 sectors. mkfs.fat
/// always rounds the FAT to 976, so the empty image is rebuilt with 975-sector
/// FATs (data start 1982). Only the used prefix is kept in memory.
const MIS_PREFIX: usize = 1982 + 8 * 3000;
fn mk_misaligned(img: &std::path::Path) {
    use std::os::unix::fs::FileExt;
    let o = Command::new("mkfs.fat").args(["-F", "32", "-s", "8", "-R", "32", "-S", "512", "-C"]).arg(img).arg("500000").output().expect("mkfs.fat");
    assert!(o.status.success());
    let f = std::fs::OpenOptions::new().read(true).write(true).open(img).unwrap();
    let mut res = vec![0u8; 32 * SS];
    f.read_exact_at(&mut res, 0).unwrap();
    let mut fat = vec![0u8; 975 * SS];
    f.read_exact_at(&mut fat, 32 * SS as u64).unwrap();
    for s in [0usize, 6] {
        res[s * SS + 32..s * SS + 36].copy_from_slice(&1_000_000u32.to_le_bytes());
        res[s * SS + 36..s * SS + 40].copy_from_slice(&975u32.to_le_bytes());
    }
    f.write_all_at(&res, 0).unwrap();
    f.write_all_at(&fat, 32 * SS as u64).unwrap();
    f.write_all_at(&fat, 1007 * SS as u64).unwrap();
    f.write_all_at(&vec![0u8; 16 * SS], 1982 * SS as u64).unwrap(); // root cluster + next
    f.set_len(1_000_000 * SS as u64).unwrap();
}
fn mk_card_g(fill_root: usize, mis: bool) -> Card {
    let img = tmp(&format!("card{}{}.img", fill_root, if mis { "m" } else { "" }));
    let _ = std::fs::remove_file(&img);
    if mis {
        mk_misaligned(&img);
    } else {
        let o = Command::new("mkfs.fat").args(["-F", "32", "-s", "8", "-R", "32", "-S", "512", "-C"]).arg(&img).arg("40960").output().expect("mkfs.fat");
        assert!(o.status.success());
    }
    let (kernel, initrd) = (rnd(1, 100 * 1024), rnd(2, 40 * 1024));
    let files: Vec<(&str, Vec<u8>)> = vec![
        ("config.txt", config_txt()),
        ("kernel.img", kernel.clone()),
        ("initrd.cpio", initrd.clone()),
        ("cmdline.txt", cmdline()),
        ("bcm2712-rpi-5-b.dtb", rnd(3, 30 * 1024)),
    ];
    for (n, d) in files {
        let src = tmp("src.bin");
        std::fs::write(&src, d).unwrap();
        let o = Command::new("mcopy").env("MTOOLS_SKIP_CHECK", "1").arg("-i").arg(&img).arg(&src).arg(format!("::{}", n)).output().unwrap();
        assert!(o.status.success(), "mcopy {}", n);
    }
    assert!(Command::new("mmd").env("MTOOLS_SKIP_CHECK", "1").arg("-i").arg(&img).arg("::overlays").output().unwrap().status.success());
    for i in 0..fill_root {
        let src = tmp("src.bin");
        std::fs::write(&src, b"x").unwrap();
        assert!(Command::new("mcopy").env("MTOOLS_SKIP_CHECK", "1").arg("-i").arg(&img).arg(&src).arg(format!("::dummy{}.txt", i)).output().unwrap().status.success());
    }
    let mut b = std::fs::read(&img).unwrap();
    if mis {
        b.truncate(MIS_PREFIX * SS);
    }
    Card { img: Rc::new(RefCell::new(b)), log: Rc::new(RefCell::new(vec![])), kernel, initrd }
}
impl Card {
    fn fat(&self) -> Fat<Mem> {
        Fat::open(Mem { img: self.img.clone(), log: self.log.clone() }).unwrap()
    }
    fn fsck(&self, what: &str) {
        let p = tmp("fsck.img");
        std::fs::write(&p, &*self.img.borrow()).unwrap();
        {
            let tot = u32::from_le_bytes(self.img.borrow()[32..36].try_into().unwrap()) as u64 * SS as u64;
            let f = std::fs::OpenOptions::new().write(true).open(&p).unwrap();
            if f.metadata().unwrap().len() < tot {
                f.set_len(tot).unwrap();
            }
        }
        let o = Command::new("fsck.fat").arg("-n").arg(&p).output().unwrap();
        let t = String::from_utf8_lossy(&o.stdout).to_string() + &String::from_utf8_lossy(&o.stderr);
        // Fresh images are flagged for the small cluster count only; any structural complaint fails.
        for bad in ["differ", "Cross", "cross", "Bad", "bad", "Invalid", "invalid", "lost", "Unable"] {
            assert!(!t.contains(bad) || t.contains("less then suggested"), "fsck.fat after {}: {}", what, t);
        }
        // FSInfo is deliberately left stale (the firmware ignores it); "Auto-correcting" is only that.
        assert!(!t.contains("differ between"), "fsck FAT copies differ after {}: {}", what, t);
    }
    /// Run `op`, return the sector write log of it.
    fn record<T>(&self, op: impl FnOnce(&mut Fat<Mem>) -> R<T>) -> (R<T>, Vec<(u64, Vec<u8>)>) {
        self.log.borrow_mut().clear();
        let mut f = self.fat();
        let r = op(&mut f);
        (r, self.log.borrow().clone())
    }
}

// ----- firmware model -------------------------------------------------------

#[derive(Debug, Clone)]
struct Boot {
    kernel: String,
    initrd: String,
    cmdline: Vec<u8>,
    slot: Option<u8>,
}
fn fw(img: &Img, flag: bool) -> Result<Boot, String> {
    let mut f = Fat::open(Mem { img: img.clone(), log: Rc::new(RefCell::new(vec![])) }).map_err(|e| e.to_string())?;
    let name = if flag { "tryboot.txt" } else { "config.txt" };
    let ce = f.lookup(name).map_err(|e| e.to_string())?.ok_or(format!("no {}", name))?;
    let cfg = f.read_file(&ce).map_err(|e| e.to_string())?;
    let text = String::from_utf8_lossy(&cfg).to_string();
    let mut kv: HashMap<String, String> = HashMap::new();
    let mut all = true;
    for l in text.lines() {
        let t = l.trim();
        if t.starts_with('[') && t.ends_with(']') {
            all = t == "[all]";
            continue;
        }
        if !all || t.is_empty() || t.starts_with('#') {
            continue;
        }
        let k = t.split(|c: char| c == '=' || c.is_whitespace()).next().unwrap().to_string();
        let v = t[k.len()..].trim_start_matches(|c: char| c == '=' || c.is_whitespace()).to_string();
        kv.insert(k, v);
    }
    for need in ["arm_64bit", "kernel", "kernel_address", "initramfs"] {
        if !kv.contains_key(need) {
            return Err(format!("essential `{}` missing from the effective config", need));
        }
    }
    let mut prefix = kv.get("os_prefix").cloned().unwrap_or_default();
    let viable = |f: &mut Fat<Mem>, p: &str| !p.is_empty() && f.lookup(&format!("{}kernel.img", p)).ok().flatten().is_some() && f.lookup(&format!("{}{}", p, DTB)).ok().flatten().is_some();
    if !viable(&mut f, &prefix) {
        prefix.clear();
    }
    let rd = |f: &mut Fat<Mem>, n: &str| -> Result<Vec<u8>, String> {
        let en = f.lookup(&format!("{}{}", prefix, n)).map_err(|e| e.to_string())?.ok_or(format!("missing {}{}", prefix, n))?;
        f.read_file(&en).map_err(|e| e.to_string())
    };
    let kernel = rd(&mut f, "kernel.img")?;
    let initrd = rd(&mut f, "initrd.cpio")?;
    let cmdline = if let Some(c) = kv.get("cmdline") { rd(&mut f, c)? } else { rd(&mut f, "cmdline.txt")? };
    let slot = if prefix.is_empty() { None } else { Some(prefix.as_bytes()[7] - b'0') };
    Ok(Boot { kernel: sha(&kernel), initrd: sha(&initrd), cmdline, slot })
}
fn padded_sha(b: &[u8], cap: usize) -> String {
    let mut v = b.to_vec();
    v.resize(cap, 0);
    sha(&v)
}

/// Replay `log` onto `base`, one sector at a time, running `check` before the
/// first write, after every write, and (for sectors satisfying `tear`) with
/// that sector replaced by garbage.
fn replay(base: &[u8], log: &[(u64, Vec<u8>)], tear: impl Fn(u64) -> bool, check: impl Fn(&Img, &str)) {
    let img: Img = Rc::new(RefCell::new(base.to_vec()));
    check(&img, "before any write");
    for (k, (lba, d)) in log.iter().enumerate() {
        if tear(*lba) {
            for seed in 0..3u64 {
                let old = img.borrow()[*lba as usize * SS..(*lba as usize + 1) * SS].to_vec();
                let mut g = rnd(seed + 100 + *lba, SS);
                if seed == 2 {
                    let nasty = b"[pi4]\n\x00\x00\xff\xfe[all\n=====\nos_prefix=slots/s9/";
                    g[..nasty.len()].copy_from_slice(nasty);
                }
                img.borrow_mut()[*lba as usize * SS..(*lba as usize + 1) * SS].copy_from_slice(&g);
                check(&img, &format!("torn write #{} (sector {}, seed {})", k, lba, seed));
                img.borrow_mut()[*lba as usize * SS..(*lba as usize + 1) * SS].copy_from_slice(&old);
            }
        }
        img.borrow_mut()[*lba as usize * SS..(*lba as usize + 1) * SS].copy_from_slice(d);
        check(&img, &format!("after write #{} (sector {})", k, lba));
    }
}

