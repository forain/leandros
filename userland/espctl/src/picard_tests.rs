const KSZ: u64 = 128 * 1024;
const ISZ: u64 = 64 * 1024;

fn no_secret(t: &str) {
    assert!(!t.contains(PSK) && !t.contains("wifi.psk"), "secret leaked: {}", t);
}

#[test]
fn config_migration_layout() {
    let c = config_txt();
    assert!(c.len() > 2000 && c.len() < 2700, "{}", c.len());
    let (a, s) = migrate_a(&c).unwrap();
    assert_eq!(a.len(), c.len());
    let diff = diff_sectors(&c, &a);
    assert_eq!(diff, vec![s], "step (a) must change exactly one sector");
    let b = set_prefix(&a, 0).unwrap();
    assert_eq!(diff_sectors(&a, &b), vec![0], "step (b) must change exactly sector 0");
    assert_eq!(b.len(), c.len());
    assert_eq!(current_slot(&b), Some(0));
    // sector 0 now holds the os_prefix line and comments only
    for l in split_lines(&b[..head0(&b).unwrap()]) {
        assert!(is_comment(l) || l.starts_with(b"os_prefix="), "{}", String::from_utf8_lossy(l));
    }
    let c1 = set_prefix(&b, 2).unwrap();
    assert_eq!(diff_sectors(&b, &c1), vec![0]);
    assert_eq!(current_slot(&c1), Some(2));
    // refusals
    assert!(set_prefix(&c, 0).is_err(), "prefix before (a) must be refused");
    let mut sec = c.clone();
    sec.extend(b"[pi4]\nfoo=1\n");
    assert!(migrate_a(&sec).is_err());
    let mut dup = c.clone();
    dup.extend(b"kernel=other.img\n");
    assert!(migrate_a(&dup).is_err());
}

/// Whole life: setup, probe, migrate (a), stage s0, migrate (b), stage s1, rollback;
/// every phase replayed at every sector write.
#[test]
fn power_loss_every_sector() {
    power_loss_body(mk_card_g(0, false));
}
#[test]
fn power_loss_every_sector_misaligned() {
    let c = mk_card_g(0, true);
    assert_eq!((c.fat().data0 % 8, c.fat().data0, c.fat().fatsz), (6, 1982, 975));
    c.fsck("misaligned fresh");
    power_loss_body(c);
}
fn power_loss_body(c: Card) {
    let base0 = c.img.borrow().clone();
    let root_cmd = cmdline();
    let factory = (sha(&c.kernel), sha(&c.initrd));
    let kf = Rc::new(RefCell::new(vec![factory.0.clone()]));
    let inits = Rc::new(RefCell::new(vec![factory.1.clone()]));
    let slots_now: Rc<RefCell<Vec<(u8, String)>>> = Rc::new(RefCell::new(vec![]));
    let rc2 = root_cmd.clone();
    let (kf2, in2) = (kf.clone(), inits.clone());
    let check = move |img: &Img, w: &str| {
        let b = fw(img, false).unwrap_or_else(|e| panic!("{}: does not boot: {}", w, e));
        assert_eq!(b.cmdline, rc2, "{}: wrong cmdline loaded", w);
        assert!(kf2.borrow().contains(&b.kernel) && in2.borrow().contains(&b.initrd), "{}: boots an incomplete/unknown kernel (slot {:?})", w, b.slot);
    };
    let _ = slots_now;
    check(&c.img, "start");

    // ---- setup
    let (r, log) = c.record(|f| setup(f, &SetupOpts { ksz: KSZ, isz: ISZ, accept_root_risk: true }));
    let msg = r.unwrap();
    no_secret(&msg);
    // root sector is the last write; nothing before it touches the root dir or config files
    let rootlba = log.last().unwrap().0;
    assert!(log[..log.len() - 1].iter().all(|(l, _)| *l != rootlba), "root sector written before the end");
    replay(&base0, &log, |_| false, &check);
    c.fsck("setup");

    // ---- flag-only probe: tryboot.txt = A + cmdline line, factory kernel, noprefix marker
    let pb = fw(&c.img, true).unwrap();
    assert_eq!((pb.kernel, pb.slot), (factory.0.clone(), None));
    assert_eq!(pb.cmdline, derive_try(&root_cmd, "noprefix"));
    {
        let mut f = c.fat();
        let s = sys(&["leandros.tryboot=noprefix"], "x", &c.initrd);
        no_secret(&status(&mut f, &s).unwrap());
        // try gate: migration step is allowed, reboot requested
        let t = try_(&mut f, &s, false).unwrap();
        assert!(t.contains("migration") && *s.tried.borrow() == 1);
        // stage before commit (a) is refused
        let o = StageOpts { slot: None, kernel: c.kernel.clone(), initrd: c.initrd.clone(), tag: "TAG0".into(), sha_k: None, sha_i: None };
        let er = stage(&mut f, &s, &o).unwrap_err().to_string();
        assert!(er.contains("commit the pending migration"), "{}", er);
        // commit without the marker refused
        let er = commit(&mut f, &sys(&[], "x", &c.initrd), false).unwrap_err().to_string();
        assert!(er.contains("marker"), "{}", er);
    }

    // ---- commit (a): one sector S of config.txt, torn variants too
    let base1 = c.img.borrow().clone();
    let cfg_sec = {
        let mut f = c.fat();
        let e = f.need("config.txt").unwrap();
        f.file_lbas(&e).unwrap()
    };
    let s = sys(&["leandros.tryboot=noprefix"], "x", &c.initrd);
    let (r, log) = c.record(|f| commit(f, &s, false));
    no_secret(&r.unwrap());
    assert_eq!(log.iter().filter(|(l, _)| cfg_sec.contains(l)).count(), 1, "exactly one config.txt sector programmed");
    assert_eq!((*s.held.borrow(), *s.confirmed.borrow()), (1, 1));
    replay(&base1, &log, |l| cfg_sec.contains(&l), &check);
    c.fsck("commit-a");

    // ---- stage s0 (the good kernel), try, commit (b)
    let good = (c.kernel.clone(), c.initrd.clone());
    let s0 = sys(&["leandros.tryboot=1"], "TAGA", &good.1);
    let base2 = c.img.borrow().clone();
    let (r, log) = c.record(|f| stage(f, &s0, &StageOpts { slot: None, kernel: good.0.clone(), initrd: good.1.clone(), tag: "TAGA".into(), sha_k: Some(sha(&good.0)), sha_i: Some(sha(&good.1)) }));
    assert_eq!(r.unwrap(), 0);
    kf.borrow_mut().push(padded_sha(&good.0, KSZ as usize));
    inits.borrow_mut().push(padded_sha(&good.1, ISZ as usize));
    replay(&base2, &log, |_| false, &check);
    c.fsck("stage s0");
    let tb = fw(&c.img, true).unwrap();
    assert_eq!((tb.slot, tb.cmdline.clone()), (Some(0), derive_try(&root_cmd, "1")));
    assert_eq!(tb.kernel, padded_sha(&good.0, KSZ as usize));
    {
        let mut f = c.fat();
        assert!(try_(&mut f, &s0, true).unwrap().contains("slot s0"));
        // wrong tag refused
        let er = commit(&mut f, &sys(&["leandros.tryboot=1"], "OTHER", &good.1), false).unwrap_err().to_string();
        assert!(er.contains("tag"), "{}", er);
    }
    let base3 = c.img.borrow().clone();
    let (r, log) = c.record(|f| commit(f, &s0, false));
    no_secret(&r.unwrap());
    replay(&base3, &log, |l| cfg_sec.contains(&l), &check);
    assert_eq!(fw(&c.img, false).unwrap().slot, Some(0));
    c.fsck("commit-b");
    {
        let mut f = c.fat();
        let st = load(&mut f).unwrap();
        assert_eq!((st.infos[0].state.as_str(), st.cur), ("good", Some(0)));
    }

    // ---- stage a new build into s1 (auto skips the good slot), commit
    let newk = rnd(77, 90 * 1024);
    let s1 = sys(&["leandros.tryboot=1"], "TAGB", &good.1);
    let base4 = c.img.borrow().clone();
    let (r, log) = c.record(|f| stage(f, &s1, &StageOpts { slot: None, kernel: newk.clone(), initrd: good.1.clone(), tag: "TAGB".into(), sha_k: None, sha_i: None }));
    assert_eq!(r.unwrap(), 1);
    kf.borrow_mut().push(padded_sha(&newk, KSZ as usize));
    replay(&base4, &log, |_| false, &check);
    // the good slot is never touched by a stage
    let s0lbas = {
        let mut f = c.fat();
        let mut v = vec![];
        for n in ["kernel.img", "initrd.cpio", "info"] {
            let e = f.need(&slot_path(0, n)).unwrap();
            v.extend(f.file_lbas(&e).unwrap());
        }
        v
    };
    assert!(log.iter().all(|(l, _)| !s0lbas.contains(l)), "stage wrote into the good slot");
    assert!(log.iter().all(|(l, _)| !cfg_sec.contains(l)), "stage wrote config.txt");
    {
        let mut f = c.fat();
        // staging into the good slot is refused
        let er = stage(&mut f, &s1, &StageOpts { slot: Some(0), kernel: newk.clone(), initrd: good.1.clone(), tag: "T".into(), sha_k: None, sha_i: None }).unwrap_err().to_string();
        assert!(er.contains("good or previous"), "{}", er);
        // a foreign initrd is refused
        let er = stage(&mut f, &s1, &StageOpts { slot: None, kernel: newk.clone(), initrd: rnd(5, 1000), tag: "T".into(), sha_k: None, sha_i: None }).unwrap_err().to_string();
        assert!(er.contains("good/initrd"), "{}", er);
    }
    let base5 = c.img.borrow().clone();
    let (r, log) = c.record(|f| commit(f, &s1, false));
    r.unwrap();
    replay(&base5, &log, |l| cfg_sec.contains(&l), &check);
    assert_eq!(fw(&c.img, false).unwrap().slot, Some(1));
    c.fsck("commit s1");
    {
        let mut f = c.fat();
        let st = load(&mut f).unwrap();
        assert_eq!((st.infos[1].state.as_str(), st.infos[0].state.as_str()), ("good", "prev"));
    }

    // ---- shrink: stage a smaller kernel over the old tail (zero fill), then rollback
    let small = rnd(78, 10 * 1024);
    let s2 = sys(&["leandros.tryboot=1"], "TAGC", &good.1);
    let (r, _) = c.record(|f| stage(f, &s2, &StageOpts { slot: None, kernel: small.clone(), initrd: good.1.clone(), tag: "TAGC".into(), sha_k: None, sha_i: None }));
    assert_eq!(r.unwrap(), 2);
    {
        // stale bytes beyond the new kernel are zero
        let mut f = c.fat();
        let e = f.need(&slot_path(2, "kernel.img")).unwrap();
        let b = f.read_file(&e).unwrap();
        assert!(b[small.len()..].iter().all(|&x| x == 0) && b[..small.len()] == small[..]);
    }
    let base6 = c.img.borrow().clone();
    let (r, log) = c.record(|f| rollback(f));
    r.unwrap();
    replay(&base6, &log, |l| cfg_sec.contains(&l), &check);
    assert_eq!(fw(&c.img, false).unwrap().slot, Some(0));
    c.fsck("rollback");

    // ---- stale cmdline copy: refuse silently (no content in the message)
    {
        let mut f = c.fat();
        let e = f.need("cmdline.txt").unwrap();
        let l = f.file_lbas(&e).unwrap();
        let mut sec = f.rd(l[0], 1).unwrap();
        let p = sec.windows(PSK.len()).position(|w| w == PSK.as_bytes()).unwrap();
        sec[p] = b'Z';
        c.img.borrow_mut()[l[0] as usize * SS..l[0] as usize * SS + SS].copy_from_slice(&sec);
        let mut f = c.fat();
        let er = stage(&mut f, &s1, &StageOpts { slot: None, kernel: newk.clone(), initrd: good.1.clone(), tag: "T9".into(), sha_k: None, sha_i: None }).unwrap_err().to_string();
        assert!(er.contains("cmdline copies differ"), "{}", er);
        no_secret(&er);
        let st = status(&mut f, &s1).unwrap();
        assert!(st.contains("MISMATCH"));
        no_secret(&st);
    }
}

#[test]
fn root_sector_risk_and_dry_run() {
    // default shape: the free root entries share a sector with config.txt -> refuse
    let c = mk_card(0);
    let before = c.img.borrow().clone();
    let er = setup(&mut c.fat(), &SetupOpts { ksz: KSZ, isz: ISZ, accept_root_risk: false }).unwrap_err().to_string();
    assert!(er.contains("firmware-critical"), "{}", er);
    assert_eq!(*c.img.borrow(), before, "a refused setup must write nothing");
    // dry-run: every verb leaves the image byte-identical
    let mut f = c.fat();
    f.dry = true;
    let m = setup(&mut f, &SetupOpts { ksz: KSZ, isz: ISZ, accept_root_risk: true }).unwrap();
    assert!(m.contains("setup:"));
    assert_eq!(*c.img.borrow(), before);
    // really set up, then dry-run stage/commit/try/rollback
    setup(&mut c.fat(), &SetupOpts { ksz: KSZ, isz: ISZ, accept_root_risk: true }).unwrap();
    let s = sys(&["leandros.tryboot=noprefix"], "x", &c.initrd);
    let snap = c.img.borrow().clone();
    let mut f = c.fat();
    f.dry = true;
    commit(&mut f, &s, false).unwrap();
    assert_eq!((*s.held.borrow(), *s.confirmed.borrow()), (0, 0), "dry-run must not call hold/confirm");
    assert_eq!(*c.img.borrow(), snap);
    let t = try_(&mut f, &s, true).unwrap();
    assert!(t.contains("would") && *s.tried.borrow() == 0);
    commit(&mut c.fat(), &s, false).unwrap();
    let snap = c.img.borrow().clone();
    let mut f = c.fat();
    f.dry = true;
    stage(&mut f, &sys(&[], "T", &c.initrd), &StageOpts { slot: None, kernel: c.kernel.clone(), initrd: c.initrd.clone(), tag: "T".into(), sha_k: None, sha_i: None }).unwrap();
    assert_eq!(*c.img.borrow(), snap);
    assert!(rollback(&mut f).is_err());
    assert_eq!(*c.img.borrow(), snap);
    // allowlist: a stray write is refused
    let mut f = c.fat();
    f.allow(vec![100]).unwrap();
    assert!(f.w(0, &[0u8; SS]).is_err());
}

#[test]
fn root_in_fresh_sector_is_accepted() {
    // 12 dummy files push the end marker to the next, otherwise empty root sector
    let c = mk_card(9);
    let before = c.img.borrow().clone();
    let r = setup(&mut c.fat(), &SetupOpts { ksz: KSZ, isz: ISZ, accept_root_risk: false });
    if let Err(e) = &r {
        assert!(e.to_string().contains("firmware-critical"), "{}", e);
        return; // geometry put the end marker in the config sector anyway
    }
    assert_ne!(*c.img.borrow(), before);
    c.fsck("setup fresh-sector");
    assert!(fw(&c.img, true).is_ok());
}

#[test]
fn guard_refuses_writes_off_bootfat() {
    for v in ["setup", "stage", "try", "commit", "abort", "rollback"] {
        assert!(write_guard(v, "/dev/vdc", false).is_err());
        assert!(write_guard(v, "/dev/vdc", true).is_ok());
    }
    assert!(write_guard("status", "/dev/vdc", false).is_ok());
}
