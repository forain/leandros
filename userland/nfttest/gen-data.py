#!/usr/bin/env python3
"""Regenerate nfttest-data.h from the netavark captures (artifacts: orch/designs/podnat-capture)."""
import sys, os
cap = sys.argv[1]
names = [("a", "a_bridge_noports"), ("b", "b_port8080"), ("c", "c_range"), ("d", "d_udp_loopback"),
         ("e", "e_internal"), ("ga", "g_two_nets_a"), ("gb", "g_two_nets_b"), ("td", "b_teardown")]
out = ["/* generated by gen-data.py: `nft -j list ruleset` of netavark 1.17.2 / nftables 1.1.6 */"]
for k, d in names:
    s = open(os.path.join(cap, d, "ruleset.json")).read().strip()
    out.append("static const char cap_%s[] =" % k)
    for i in range(0, len(s), 100):
        c = s[i:i + 100].replace("\\", "\\\\").replace('"', '\\"')
        out.append('    "%s"' % c)
    out.append(";")
print("\n".join(out))
